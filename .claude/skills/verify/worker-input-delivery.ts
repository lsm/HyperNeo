const run = resolve(process.argv.at(-1)!);
assert.equal(process.env.NODE_ENV, 'test');
assert.equal(process.env.HOME, join(run, 'home'));
assert.equal(process.env.HYPERNEO_DATA_DIR, join(run, 'data'));
mkdirSync(join(run, 'evidence'), { recursive: true });
writeFileSync(join(run, 'bin/gh'), '#!/bin/sh\nexit 2\n', { mode: 0o700 });
const start = () => createDaemonApp({ config: { ...getConfig({ port: 0, host: '127.0.0.1', dbPath: join(run, 'data/daemon.db') }), disableWorktrees: true }, verbose: false });
let app = await start();
const worker = '10000000-0000-4000-8000-000000008836';
const root = 'neo:10000000-0000-4000-8000-000000008837';
const recoveringNeo = 'neo:10000000-0000-4000-8000-000000008838';
const ref = { adapter: 'hyperneo', id: worker };
const caller = { source: 'internal', role: 'neo', sessionId: root } as const;
const evidence: Record<string, unknown> = {};
const db = () => app.db.getDatabase();
const wakeInputs = () => db().prepare("UPDATE job_queue SET run_at = 0 WHERE queue = 'worker_input' AND status = 'pending'").run();
const state = (status: string) => {
  db().prepare('UPDATE sessions SET processing_state = ? WHERE id = ?').run(JSON.stringify({ status }), worker);
  if (status === 'idle') wakeInputs();
};
const inputs = () => db().prepare('SELECT id, message, outcome, deadline_at AS deadline FROM work_delivery_inputs ORDER BY accepted_at, rowid').all() as { id: string; message: string; outcome: string | null; deadline: number }[];
const messages = (sessionId = worker) => (db().prepare(`SELECT ${sdkMessageBodyAt('m.rowid')} AS body FROM sdk_messages m WHERE session_id=? AND message_type='user' ORDER BY seq`).all(sessionId) as { body: string }[]).map((row) => hyperneoInputText(row.body));
const until = async (condition: () => boolean, label: string) => {
  const deadline = Date.now() + 15000;
  while (!condition() && Date.now() < deadline) await new Promise((done) => setTimeout(done, 25));
  assert(condition(), `${label}: ${JSON.stringify(db().prepare("SELECT queue,status,error,result,payload FROM job_queue WHERE queue = 'worker_input'").all())}`);
};
try {
  assert(![8399, 8499].includes(app.server.port));
  for (const id of [root, worker]) await app.db.createSession({ id, title: 'Synthetic delivery proof', workspacePath: run, createdAt: new Date().toISOString(), lastActiveAt: new Date().toISOString(), status: 'active', config: { queryMode: 'manual' }, metadata: { messageCount: 0, totalTokens: 0, inputTokens: 0, outputTokens: 0, totalCost: 0, toolCallCount: 0 } });
  new NeoRepository(db()).reserveBinding({ sessionId: root, kind: 'neo', projectId: null });
  const registry = app.sessionManager.getOperationRegistry();
  await invokeOperation(registry, 'work.status', { ref }, caller);
  state('processing');
  evidence.busyStatus = await invokeOperation(registry, 'work.status', { ref }, caller);
  assert.match(JSON.stringify(evidence.busyStatus), /\"status\":\"running\"/);
  const first = await invokeOperation(registry, 'work.send', { ref, notice: true, message: 'First retained follow-up' }, caller);
  const second = await invokeOperation(registry, 'work.send', { ref, notice: true, message: 'Second retained follow-up' }, caller);
  for (const accepted of [first, second]) {
    assert.equal(accepted.kind, 'completed');
    assert(accepted.kind === 'completed');
    const result = SendWorkResultSchema.parse(accepted.value);
    assert(result.ok && !result.value.delivered && result.value.inputId);
  }
  await until(() => !!db().prepare("SELECT 1 FROM job_queue WHERE queue='worker_input' AND error LIKE 'Waiting for the current%'").get(), 'busy input is parked');
  assert.equal(inputs().length, 2);
  assert(inputs().every((input) => input.outcome === null && input.deadline > Date.now() + 60000));
  assert.equal(messages().length, 0);
  evidence.beforeRestart = inputs();
  await app.cleanup();
  app = await start();
  assert(![8399, 8499].includes(app.server.port));
  assert.equal(inputs().length, 2);
  assert(inputs().every((input) => input.outcome === null));
  state('idle');
  await until(() => inputs()[0].outcome !== null, 'first input dispatches after restart and turn completion');
  await until(() => messages().some((text) => text.includes('First retained follow-up')), 'first input reaches the SDK receiver');
  state('idle');
  await until(() => inputs()[1].outcome !== null, 'second input dispatches');
  await until(() => messages().some((text) => text.includes('Second retained follow-up')), 'second input reaches the SDK receiver');
  const received = messages().filter((text) => text.includes('retained follow-up'));
  assert.equal(received.length, 2);
  assert(received[0].includes('First retained follow-up'));
  assert(received[1].includes('Second retained follow-up'));
  assert(inputs().every((input) => input.deadline < Date.now() + 31000));
  evidence.afterRestart = inputs();
  evidence.received = received;
  await app.jobProcessor.stop();
  const uncertain = await invokeOperation(app.sessionManager.getOperationRegistry(), 'work.send', { ref, notice: true, message: 'Retain the interrupted dispatch' }, { ...caller, sessionId: recoveringNeo });
  assert(uncertain.kind === 'completed' && SendWorkResultSchema.parse(uncertain.value).ok);
  const claimed = app.jobQueue.dequeue('worker_input', 1)[0];
  assert(claimed);
  assert(await app.db.gateway.call(workerInputWrites, 'dispatch', claimed));
  app.jobQueue.requeueWaiting(claimed.id, Date.now(), claimed.claimToken!);
  await app.cleanup();
  app = await start();
  await until(() => inputs()[2].outcome !== null && app.jobQueue.getJob(claimed.id)?.status === 'pending', 'interrupted dispatch failure is retained while its recipient is unavailable');
  assert.equal(app.jobQueue.getJob(claimed.id)?.retryCount, 0);
  evidence.notificationPending = { input: inputs()[2], job: app.jobQueue.getJob(claimed.id) };
  await app.db.createSession({ id: recoveringNeo, title: 'Recovered synthetic Neo', workspacePath: run, createdAt: new Date().toISOString(), lastActiveAt: new Date().toISOString(), status: 'active', config: { queryMode: 'manual' }, metadata: { messageCount: 0, totalTokens: 0, inputTokens: 0, outputTokens: 0, totalCost: 0, toolCallCount: 0 } });
  wakeInputs();
  await until(() => app.jobQueue.getJob(claimed.id)?.status === 'completed', 'the notification completes after its recipient recovers');
  await until(() => messages(recoveringNeo).some((text) => text.includes('dispatch was interrupted')), 'Neo receives the uncertainty report');
  assert.equal(messages().filter((text) => text.includes('Retain the interrupted dispatch')).length, 0);
  const uncertaintyReports = messages(recoveringNeo).filter((text) => text.includes('dispatch was interrupted'));
  assert.equal(uncertaintyReports.length, 1);
  assert.equal(inputs()[2].message, 'Retain the interrupted dispatch');
  assert.match(inputs()[2].outcome!, /may not have reached/);
  evidence.uncertainty = { input: inputs()[2], reports: uncertaintyReports };
  const todos = new NeoAskTodoRepository(db());
  const sessions = new NeoTodoSessionRepository(db());
  const now = Date.now();
  todos.openAsk({ id: 'queued-answer-ask', title: 'Synthetic queued answer', request: 'Prove answer admission', sessionId: root, projectId: null, originMessageId: null, createdAt: now });
  const todo = todos.addTodo('queued-answer-todo', 'queued-answer-ask', { title: 'Synthetic question task', doneWhen: 'The answer is admitted', instruction: 'Wait for the answer', check: null, named: null }, now);
  const source = { ...ref, name: 'Synthetic worker', label: 'Synthetic worker', provider: 'Synthetic', link: null };
  sessions.bind(todo.id, source, now);
  todos.updateTodo(todo, { state: 'doing', startedAt: now }, now);
  const writeQuestion = createNeoWorkerQuestionWriter(todos, sessions, () => 'en', async () => source);
  const question = await writeQuestion(source, { todoId: todo.id, kind: 'blocked', title: 'Choose the next step', options: ['Proceed', 'Wait'], language: 'en', report: 'Need the human answer' });
  assert(question.ok);
  state('processing');
  const answerProcess = Bun.spawn([process.execPath, join(import.meta.dir, 'rpc.ts'), 'neo.question.answer', JSON.stringify({ questionId: question.question.id, answer: ['Proceed'] })], { env: { ...process.env, VERIFY_PORT: String(app.server.port) }, stdout: 'pipe', stderr: 'inherit' });
  const answered = JSON.parse(await new Response(answerProcess.stdout).text());
  assert.equal(await answerProcess.exited, 0);
  assert(!answered.reply.error, JSON.stringify(answered));
  assert((answered.reply.value ?? answered.reply).ok, JSON.stringify(answered));
  assert.equal(todos.questionAnswers.list(question.question.id)[0].state, 'pending');
  assert.equal(todos.getTodo(todo.id)?.blockedBy, 'needs-human');
  evidence.questionPending = todos.questionAnswers.list(question.question.id);
  state('idle');
  await until(() => sessions.inputs.list(todo.id).some((input) => input.outcome && 'ref' in input.outcome), 'question answer receives native admission');
  app.jobQueue.enqueue({ queue: 'neo.work.driver.refresh', payload: { scope: 'neo' }, runAt: Date.now() });
  await until(() => todos.questionAnswers.list(question.question.id)[0].state === 'accepted', 'driver refresh confirms the stored answer admission');
  assert.equal(todos.getTodo(todo.id)?.blockedBy, null);
  await until(() => messages().some((text) => text.includes('[worker-answer:')), 'the answer reaches the SDK inbox');
  evidence.questionAccepted = todos.questionAnswers.list(question.question.id);
  const waitingId = await app.db.gateway.call(workerInputWrites, 'accept', { ref: { adapter: 'synthetic-unavailable', id: 'synthetic-worker' }, message: 'Retain this unknown worker input' }, `session:${root}`, caller);
  const waitingJob = () => app.jobQueue.listJobs({ queue: 'worker_input' }).find((job) => job.payload.inputId === waitingId)!;
  await until(() => waitingJob().payload.waitReported === true, 'the unknown worker wait is reported');
  const waitingReason = waitingJob().error!;
  await until(() => messages(root).some((text) => text.includes(waitingReason)), 'the originating Neo receives the waiting reason');
  assert.equal(waitingJob().status, 'pending');
  assert.equal(waitingJob().retryCount, 0);
  assert.equal(inputs().find((input) => input.id === waitingId)?.outcome, null);
  await app.cleanup();
  app = await start();
  wakeInputs();
  const previousRun = waitingJob().runAt;
  await until(() => waitingJob().runAt > previousRun, 'the retained unknown input retries after restart');
  const waitingReports = messages(root).filter((text) => text.includes(waitingReason));
  assert.equal(waitingReports.length, 1);
  assert.equal(waitingJob().payload.waitReported, true);
  assert.equal(waitingJob().status, 'pending');
  assert.equal(inputs().find((input) => input.id === waitingId)?.outcome, null);
  evidence.waiting = { input: inputs().find((input) => input.id === waitingId), job: waitingJob(), reports: waitingReports };
  const refusedIds: string[] = [];
  for (let attempt = 0; attempt < 2; attempt++) {
    const id = await app.db.gateway.call(workerInputWrites, 'accept', { ref: { adapter: 'hyperneo', id: 'synthetic-retired-worker' }, message: 'The same synthetic answer', idempotencyKey: 'synthetic-answer' }, `session:${root}`, caller);
    refusedIds.push(id);
    await until(() => app.jobQueue.listJobs({ queue: 'worker_input' }).some((job) => job.payload.inputId === id && job.status === 'completed'), 'the answer refusal is reported and settled');
  }
  const refusal = JSON.parse(inputs().find((input) => input.id === refusedIds[0])!.outcome!).failure;
  await until(() => messages(root).some((text) => text.includes(refusal)), 'Neo receives the answer refusal');
  const refusalReports = messages(root).filter((text) => text.includes(refusal));
  assert.equal(refusalReports.length, 1);
  evidence.refusedAnswers = { inputs: inputs().filter((input) => refusedIds.includes(input.id)), reports: refusalReports };
  evidence.port = app.server.port;
  evidence.passed = true;
  console.log(JSON.stringify({ passed: true, accepted: inputs().length, received: received.length, uncertaintyReports: uncertaintyReports.length, notificationRecovered: true, questionAccepted: true, restartRecovered: true, waitingReports: waitingReports.length, refusalReports: refusalReports.length }));
} finally {
  await app.cleanup();
  writeFileSync(join(run, 'evidence/observed.json'), JSON.stringify(evidence, null, 2));
}
