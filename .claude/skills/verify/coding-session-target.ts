process.env.HYPERNEO_SPACE ??= 'on';
import assert from 'node:assert/strict';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { createDaemonApp } from '../../../packages/daemon/src/app.ts';
import { getConfig } from '../../../packages/daemon/src/config.ts';
import { createLocalSocket } from '../../../packages/daemon/src/lib/pairing/local-credential.ts';
import { NeoAskTodoRepository } from '../../../packages/daemon/src/storage/repositories/neo-ask-todo-repository.ts';
import { NeoTodoSessionRepository } from '../../../packages/daemon/src/storage/repositories/neo-todo-session-repository.ts';
import { createNeoService } from '../../../packages/daemon/tests/unit/helpers/neo-service.ts';
import type { WorkRef } from '../../../packages/daemon/src/lib/drivers/types.ts';

const run = resolve(process.argv[2]);
assert.equal(process.env.NODE_ENV, 'test');
assert.equal(process.env.HOME, join(run, 'home'));
assert.equal(process.env.HYPERNEO_DATA_DIR, join(run, 'data'));
assert(!existsSync(join(run, 'data')));
mkdirSync(join(run, 'evidence'), { recursive: true });
mkdirSync(join(run, 'workspace'), { recursive: true });
const evidence: unknown[] = [];
const repo = 'github.com/synthetic/sessions';
const network = globalThis.fetch;
globalThis.fetch = (() => { throw new Error('No HTTP in synthetic session target proof'); }) as typeof fetch;
const app = await createDaemonApp({ config: { ...getConfig({ port: 0, host: '127.0.0.1', dbPath: join(run, 'data/daemon.db') }), disableWorktrees: true }, verbose: false });
let ws: WebSocket | undefined;
try {
  await app.spaceRuntimeService.ready(); await app.jobProcessor.stop(); assert(![8399, 8499].includes(app.server.port));
  await app.db.updateGlobalSettings({ neo: { packs: ['coding'] } });
  ws = createLocalSocket(`ws://127.0.0.1:${app.server.port}/ws`);
  await new Promise<void>((done, fail) => { ws!.onopen = () => done(); ws!.onerror = () => fail(new Error('RPC connection failed')); });
  const pending = new Map<string, (reply: { error?: unknown; data?: unknown }) => void>();
  ws.onmessage = event => { const reply = JSON.parse(String(event.data)); pending.get(reply.requestId ?? reply.id)?.(reply); };
  const rpc = (method: string, data: unknown) => new Promise<unknown>((done, fail) => {
    const id = crypto.randomUUID(), timer = setTimeout(() => fail(new Error('RPC timeout')), 10000);
    pending.set(id, reply => {
      pending.delete(id); clearTimeout(timer); evidence.push({ method, data, reply });
      if (reply.error) fail(new Error(JSON.stringify(reply.error))); else done(reply.data);
    });
    ws!.send(JSON.stringify({ id, type: 'REQ', sessionId: 'global', method, data, timestamp: new Date().toISOString(), version: '1.0.0' }));
  });
  const session = async (title: string): Promise<WorkRef> => ({ adapter: 'hyperneo', id: ((await rpc('session.create', { title, workspacePath: join(run, 'workspace'), config: { queryMode: 'manual' } })) as { sessionId: string }).sessionId });
  const status = async (ref: WorkRef) => ({ kind: 'completed' as const, value: await rpc('operation.invoke', { name: 'work.status', input: { ref } }) });
  const [front, back] = [await session('frontend'), await session('backend')];
  const neo = createNeoService(app.db, app.sessionManager, app.messageHub, app.internalEventBus);
  const pack = neo.packs().find((candidate) => candidate.id === 'coding');
  assert(pack?.workerTarget, 'the coding pack declares workerTarget');
  const db = app.db.getDatabase();
  const store = new NeoAskTodoRepository(db);
  for (const id of ['feature', 'earlier'])
    store.openAsk({ id, projectId: null, sessionId: 'neo', originMessageId: null, title: id, request: 'Synthetic', createdAt: 1 });
  const todo = (askId: string) => store.addTodo(crypto.randomUUID(), askId, { title: 'Slice', instruction: 'Synthetic', named: null, check: null, doneWhen: 'Done' }, 2, repo);
  const worked = (askId: string, ref: WorkRef, name?: string) => {
    const item = todo(askId);
    db.prepare('INSERT INTO neo_todo_sessions (todo_id, target, ref) VALUES (?, ?, ?)').run(item.id, JSON.stringify(name ? { verb: 'start', adapter: 'hyperneo', name } : { verb: 'send', ref }), JSON.stringify(ref));
    db.prepare("UPDATE neo_todos SET state = 'done' WHERE id = ?").run(item.id);
    return item;
  };
  const decide = async (label: string, item: ReturnType<typeof todo>, target: Parameters<NonNullable<typeof pack.workerTarget>>[1]) => {
    const decision = await pack.workerTarget!(item, target, status, async () => ({ kind: 'completed' as const, value: { ok: true } }));
    evidence.push({ surface: 'coding pack workerTarget', label, target, decision });
    return decision;
  };
  worked('earlier', front, 'frontend');
  worked('earlier', back, 'backend');
  const first = todo('feature');
  assert.deepEqual(await decide('unrelated work reuses the idle backend session', first, { verb: 'start', adapter: 'hyperneo', name: 'backend' }), { value: { verb: 'send', ref: back } });
  db.prepare('INSERT INTO neo_todo_sessions (todo_id, target) VALUES (?, ?)').run(first.id, JSON.stringify({ verb: 'send', ref: back }));
  assert.deepEqual(await decide('a later slice of the feature follows it', todo('feature'), { verb: 'start', adapter: 'hyperneo' }), { value: { verb: 'send', ref: back } });
  const missing = { adapter: 'hyperneo', id: 'no-such-session' };
  store.openAsk({ id: 'lost', projectId: null, sessionId: 'neo', originMessageId: null, title: 'lost', request: 'Synthetic', createdAt: 1 });
  const lost = todo('lost');
  db.prepare('INSERT INTO pack_coding_feature_sessions (repo, feature_key, todo_id, reserved_at) VALUES (?, ?, ?, 1)').run(repo.toLowerCase(), 'lost', lost.id);
  db.prepare('INSERT INTO neo_todo_sessions (todo_id, target, ref) VALUES (?, ?, ?)').run(lost.id, JSON.stringify({ verb: 'send', ref: missing }), JSON.stringify(missing));
  const waited = await decide('an unreachable feature session waits', todo('lost'), { verb: 'start', adapter: 'hyperneo' });
  assert('reason' in waited && waited.reason.startsWith('session_unknown'));
  const sessions = new NeoTodoSessionRepository(db);
  const ready = (askId: string) => {
    const item = store.addTodo(crypto.randomUUID(), askId, { approvedAt: 1, title: 'Next slice', instruction: 'Synthetic next slice; reply ok.', named: null, check: { pack: 'coding', kind: 'pr_merged', params: {} }, doneWhen: 'Done' }, 3, repo);
    sessions.create(item.id, { verb: 'start', adapter: 'hyperneo', name: 'backend' });
    return item;
  };
  const dispatched = async (label: string, item: ReturnType<typeof todo>) => {
    const outcome = await neo.todoRunner.start(item.id);
    const row = { surface: 'todo runner start', label, outcome, todo: store.getTodo(item.id), target: sessions.get(item.id), ref: sessions.readRef(item.id) };
    evidence.push(row);
    return row;
  };
  const reused = await dispatched('a ready slice of the feature is sent to its backend session', ready('feature'));
  assert.equal(reused.todo?.state, 'doing');
  assert.deepEqual(reused.target, { verb: 'send', ref: back });
  assert.deepEqual(reused.ref, back);
  const held = await dispatched('a ready slice of the unreachable feature waits', ready('lost'));
  assert.equal(held.todo?.state, 'todo');
  assert(held.todo?.reason?.includes('session_unknown'));
  assert.deepEqual(held.target, { verb: 'start', adapter: 'hyperneo', name: 'backend' });
  assert.equal(held.ref, null);
  const reserve = (askId: string, todoId: string) => db.prepare('INSERT INTO pack_coding_feature_sessions (repo, feature_key, todo_id, reserved_at) VALUES (?, ?, ?, 1)').run(repo.toLowerCase(), askId, todoId);
  const reserved = (askId: string) => db.prepare('SELECT todo_id AS todoId FROM pack_coding_feature_sessions WHERE feature_key = ?').all(askId);
  for (const id of ['failed', 'refused'])
    store.openAsk({ id, projectId: null, sessionId: 'neo', originMessageId: null, title: id, request: 'Synthetic', createdAt: 1 });
  const failed = ready('failed');
  reserve('failed', failed.id);
  db.prepare("UPDATE neo_todos SET state = 'removed' WHERE id = ?").run(failed.id);
  const after = await decide('a sessionless removed owner no longer holds its feature', todo('failed'), { verb: 'start', adapter: 'hyperneo' });
  assert(!('reason' in after), JSON.stringify(after));
  assert(pack.workerTargetRefused, 'the coding pack declares workerTargetRefused');
  const refused = ready('refused');
  reserve('refused', refused.id);
  await pack.workerTargetRefused(refused);
  evidence.push({ surface: 'coding pack workerTargetRefused', label: 'a refused claim drops its unbound reservation', reserved: reserved('refused') });
  assert.deepEqual(reserved('refused'), []);
  reserve('refused', reused.todo!.id);
  await pack.workerTargetRefused(reused.todo!);
  assert.deepEqual(reserved('refused'), [{ todoId: reused.todo!.id }]);
  for (const ref of [front, back]) await rpc('session.archive', { sessionId: ref.id, confirmed: true });
  db.prepare('DELETE FROM neo_todo_sessions WHERE ref = ?').run(JSON.stringify(missing));
  const archivedStatus = await status(back);
  evidence.push({ surface: 'work.status', label: 'an archived session reports stopped', status: archivedStatus });
  assert.equal((archivedStatus.value as { value?: { status?: string } }).value?.status, 'stopped', JSON.stringify(archivedStatus));
  store.openAsk({ id: 'after-archive', projectId: null, sessionId: 'neo', originMessageId: null, title: 'after-archive', request: 'Synthetic', createdAt: 1 });
  const restarted = todo('after-archive');
  const onlyArchived = await decide('only archived sessions: a new session starts', restarted, { verb: 'start', adapter: 'hyperneo', name: 'backend' });
  assert.equal('value' in onlyArchived && onlyArchived.value.verb, 'start', JSON.stringify(onlyArchived));
  assert.deepEqual(reserved('after-archive'), [{ todoId: restarted.id }], 'the fresh start owns the feature');
  const next = await session('next');
  db.prepare('INSERT INTO neo_todo_sessions (todo_id, target, ref) VALUES (?, ?, ?)').run(restarted.id, JSON.stringify({ verb: 'send', ref: next }), JSON.stringify(next));
  db.prepare("UPDATE neo_todos SET state = 'done' WHERE id = ?").run(restarted.id);
  await rpc('session.archive', { sessionId: next.id, confirmed: true });
  const fresh = await session('fresh');
  worked('earlier', fresh, 'dev');
  const moved = todo('after-archive');
  assert.deepEqual(await decide('archived owner and live idle: the live one is reused', moved, { verb: 'start', adapter: 'hyperneo', name: 'dev' }), { value: { verb: 'send', ref: fresh } });
  assert.deepEqual(reserved('after-archive'), [{ todoId: moved.id }], 'the live session takes the feature over');
  console.log(`PASS: on a live daemon the coding pack reuses an idle work-type session, sends a feature's later slice to it, and waits when the feature's session status is unknown; todo start sent the ready slice to the backend session and recorded that send, and held the unreachable feature's slice as a todo with its start target; a sessionless failed owner and a refused claim's unbound reservation stop holding their feature, while a started todo keeps its reservation; archived sessions are never reused: with only archived ones a new session starts and owns the feature, and when the owner's session is archived a live idle one is chosen and takes the feature over. Evidence: ${run}/evidence/session-target.json`);
} finally {
  writeFileSync(join(run, 'evidence/session-target.json'), JSON.stringify(evidence, null, 2));
  ws?.close(); await app.cleanup();
  globalThis.fetch = network;
}
