import assert from 'node:assert/strict';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { spawn } from 'node:child_process';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createDaemonApp } from '../../../packages/daemon/src/app.ts';
import { getConfig } from '../../../packages/daemon/src/config.ts';
import { installRecoveryWait } from './tool-recovery-writer-wait.ts';

const run = process.argv.at(-1)!;
const whitespace = process.argv.includes('whitespace');
assert(run.startsWith('/private/tmp/'));
assert.equal(process.env.NODE_ENV, 'test');
assert.equal(process.env.HOME, join(run, 'home'));
assert.equal(process.env.HYPERNEO_DATA_DIR, join(run, 'data'));
mkdirSync(join(run, 'evidence'), { recursive: true });
const NativeWorker = globalThis.Worker;
const fixture = join(run, 'writer.ts');
writeFileSync(fixture, `import { installRecoveryWait } from ${JSON.stringify(pathToFileURL(resolve('.claude/skills/verify/tool-recovery-writer-wait.ts')).href)}; installRecoveryWait(${JSON.stringify(run)}, 'worker', ${whitespace}); const pending=[]; globalThis.onmessage=e=>pending.push(e); await import(${JSON.stringify(pathToFileURL(resolve('packages/daemon/src/storage/db-gateway/db-gateway-worker.ts')).href)}); const dispatch=globalThis.onmessage; for(const event of pending) dispatch(event);`);
globalThis.Worker = function(url: string | URL, options?: WorkerOptions) {
  return new NativeWorker(String(url).endsWith('/db-gateway-worker.ts') ? pathToFileURL(fixture).href : url, options);
} as unknown as typeof Worker;
let app: Awaited<ReturnType<typeof createDaemonApp>> | undefined;
let socket: WebSocket | undefined;
let probe: ReturnType<typeof spawn> | undefined;
const evidence: Record<string, unknown> = { runtime: Bun.version, modeledWaitMs: 1200, whitespace };
try {
  app = await createDaemonApp({ config: { ...getConfig({ host: '127.0.0.1', port: 0, dbPath: join(run, 'data/daemon.db'), workspaceRoot: run }), disableWorktrees: true }, verbose: false });
  await app.jobProcessor.stop();
  assert.notEqual(app.server.port, 8399);
  const url = `ws://127.0.0.1:${app.server.port}/ws`;
  socket = new WebSocket(url);
  await new Promise<void>((done, fail) => { socket!.onopen=()=>done(); socket!.onerror=()=>fail(new Error('RPC connection failed')); });
  const pending = new Map<string, { done(value: unknown): void; fail(error: Error): void }>();
  socket.onmessage = ({data}) => { const reply=JSON.parse(String(data)); const entry=pending.get(reply.requestId ?? reply.id); if(entry) { pending.delete(reply.requestId ?? reply.id); reply.error ? entry.fail(new Error(JSON.stringify(reply.error))) : entry.done(reply.data); } };
  const rpc = (method: string, data: unknown) => new Promise<unknown>((done, fail) => {
    const id=crypto.randomUUID(), timer=setTimeout(()=>{pending.delete(id);fail(new Error(`timeout: ${method}`));},10000);
    pending.set(id,{done: value=>{clearTimeout(timer);done(value);},fail:error=>{clearTimeout(timer);fail(error);}});
    socket!.send(JSON.stringify({id,type:'REQ',sessionId:'global',method,data,timestamp:new Date().toISOString(),version:'1.0.0'}));
  });
  const { sessionId } = await rpc('session.create', { workspacePath: run, config: { queryMode: 'manual' } }) as { sessionId: string };
  await app.spaceRuntimeService.ready();
  probe = spawn(process.execPath, ['-e', `const ws=new WebSocket(${JSON.stringify(url)});let stop=false,id=0,at=0;const samples=[];const send=()=>{if(stop){console.log(JSON.stringify({samples}));ws.close();return;}at=performance.now();ws.send(JSON.stringify({id:String(++id),type:'REQ',method:'system.health',data:{},sessionId:'global',version:'1.0.0',timestamp:new Date().toISOString()}));};ws.onopen=()=>{console.log('READY');send();};ws.onmessage=e=>{const r=JSON.parse(e.data);if((r.requestId??r.id)!==String(id))return;if(r.error)throw new Error(JSON.stringify(r.error));samples.push(performance.now()-at);setTimeout(send,10);};process.stdin.on('data',()=>{stop=true;});setTimeout(()=>process.exit(2),20000).unref();`], { env:process.env, stdio:['pipe','pipe','pipe'] });
  let output='', errors='';
  probe.stdout!.on('data',data=>{output+=String(data);}); probe.stderr!.on('data',data=>{errors+=String(data);});
  const exited=new Promise((done,fail)=>{probe!.once('exit',done);probe!.once('error',fail);});
  for(let n=0;!output.includes('READY') && n<500;n++) await Bun.sleep(10);
  assert(output.includes('READY'),errors);
  const fixturePrepare = app.db.getDatabase().prepare.bind(app.db.getDatabase());
  installRecoveryWait(run, 'main', whitespace);
  const toolUseId = crypto.randomUUID();
  const created = await app.internalEventBus.publish('sdk.toolUse.created', { sessionId, toolUseId, toolName: 'Bash', timestamp: Date.now() });
  assert.deepEqual(created.failures, []); assert(created.delivered > 0);
  const row = () => app!.db.getDatabase().prepare('SELECT status, session_id AS sessionId FROM tool_continuation_recovery WHERE tool_use_id=?').get(toolUseId);
  assert.deepEqual(row(), { status: 'active', sessionId });
  const consumed = await app.internalEventBus.publish('sdk.toolUse.consumed', { sessionId, toolUseId, timestamp: Date.now() });
  assert.deepEqual(consumed.failures, []); assert(consumed.delivered > 0);
  assert.deepEqual(row(), { status: 'consumed', sessionId });
  const expiredTool = crypto.randomUUID();
  const due = await app.internalEventBus.publish('sdk.toolUse.created', { sessionId, toolUseId: expiredTool, toolName: 'Bash', timestamp: Date.now() });
  assert.deepEqual(due.failures, []);
  fixturePrepare('UPDATE tool_continuation_recovery SET expires_at=0 WHERE tool_use_id=?').run(expiredTool);
  await app.spaceRuntimeService.getSpaceRuntime().executeTick();
  assert.deepEqual(fixturePrepare('SELECT status FROM tool_continuation_recovery WHERE tool_use_id=?').get(expiredTool), { status: 'expired' });
  probe.stdin!.end('stop'); assert.equal(await exited,0,errors);
  const health=JSON.parse(output.trim().split('\n').at(-1)!).samples as number[];
  const writes=readFileSync(join(run,'evidence/recovery-sql.jsonl'),'utf8').trim().split('\n').map(line=>JSON.parse(line));
  Object.assign(evidence,{created,consumed,maxHealthMs:Math.max(...health),healthReplies:health.length,writes});
  assert(writes.some(row=>row.operation==='run' && row.sql.trimStart().startsWith('INSERT')));
  const delayed = writes.filter(row => row.modeledWaitMs > 0);
  assert.equal(delayed.length, 1, 'Exactly one recovery insert must exercise the storage wait');
  assert.equal(delayed[0].modeledWaitMs, 1200);
  assert(delayed[0].waitElapsedMs >= 1100, 'The modeled wait did not execute');
  assert(writes.every(row=>row.thread==='worker'),'Tool recovery writes still run on main');
  assert(Number(evidence.maxHealthMs)<250, 'health delayed by recovery writes');
  evidence.passed=true;
} finally {
  socket?.close(); probe?.kill(); await app?.cleanup(); globalThis.Worker=NativeWorker;
  writeFileSync(join(run,'evidence/observed.json'),JSON.stringify(evidence,null,2));
}
