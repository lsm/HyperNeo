import assert from 'node:assert/strict';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import type { Session } from '../../../packages/shared/src/mod.ts';
import { prepareInitialSessionToolSelection, projectSessionToolInputs } from '../../../packages/daemon/src/lib/tools/session-tool-inputs.ts';
import { changeSessionToolChoice, type SessionToolChoiceChangeDependencies } from '../../../packages/daemon/src/lib/tools/change-session-tool-choice.ts';
import { translateLegacyToolPreference, projectLegacyToolDefaultUpdate, selectSessionToolDefaults } from '../../../packages/daemon/src/lib/tools/legacy-tool-preferences.ts';
import { pinnedSlotVetoes } from '../../../packages/daemon/src/storage/repositories/session-tool-selection-migration.ts';
import { Client } from '../../../packages/daemon/node_modules/@modelcontextprotocol/sdk/dist/esm/client/index.js';
import { Server } from '../../../packages/daemon/node_modules/@modelcontextprotocol/sdk/dist/esm/server/index.js';
import { InMemoryTransport } from '../../../packages/daemon/node_modules/@modelcontextprotocol/sdk/dist/esm/inMemory.js';
import { ListToolsRequestSchema } from '../../../packages/daemon/node_modules/@modelcontextprotocol/sdk/dist/esm/types.js';

const run=resolve(process.argv[2]);
assert.equal(process.env.NODE_ENV,'test');
assert.equal(process.env.HOME,join(run,'home'));
assert.equal(process.env.HYPERNEO_DATA_DIR,join(run,'data'));
assert(!existsSync(join(run,'data')));
for(const name of ['home','workspace','evidence']) mkdirSync(join(run,name),{recursive:true});
const {createDaemonApp}=await import('../../../packages/daemon/src/app.ts');
const {getConfig}=await import('../../../packages/daemon/src/config.ts');
const {MessageHub,WebSocketClientTransport}=await import('../../../packages/shared/src/mod.ts');
const mcp=new Server({name:'synthetic-browser',version:'1'},{capabilities:{tools:{}}});
mcp.setRequestHandler(ListToolsRequestSchema,async()=>({tools:[{name:'navigate',inputSchema:{type:'object'}}]}));
const client=new Client({name:'synthetic-projection',version:'1'});
const [a,b]=InMemoryTransport.createLinkedPair();
await mcp.connect(a);
await client.connect(b);
let app:Awaited<ReturnType<typeof createDaemonApp>>|undefined;
let transport:InstanceType<typeof WebSocketClientTransport>|undefined;
const evidence:Record<string,unknown>={activeConsumerWired:false,sdkApplyVerified:false,queryStarted:false};
try {
  app=await createDaemonApp({config:{...getConfig({host:'127.0.0.1',port:0,dbPath:join(run,'data/daemon.db'),workspaceRoot:join(run,'workspace')}),disableWorktrees:true,disableGoalProcessing:true},verbose:false});
  assert.notEqual(app.server.port,8399);
  const hub=new MessageHub({defaultSessionId:'global'});
  transport=new WebSocketClientTransport({url:`ws://127.0.0.1:${app.server.port}/ws`,autoReconnect:false});
  hub.registerTransport(transport);
  await transport.initialize();
  const registry=await hub.request<{servers:{id:string}[]}>('mcp.registry.list',{});
  for(const server of registry.servers) await hub.request('mcp.registry.setEnabled',{id:server.id,enabled:false});
  const {server}=await hub.request<{server:{id:string}}>('mcp.registry.create',{name:'fixture-registry',sourceType:'stdio',command:'not-executed',enabled:false,env:{FIXTURE_ONLY:'synthetic'}});
  const {skill:wrapper}=await hub.request<{skill:{id:string}}>('skill.create',{params:{name:'fixture-wrapper',displayName:'Fixture wrapper',description:'Fixture only',sourceType:'mcp_server',config:{type:'mcp_server',appMcpServerId:server.id},enabled:false,validationStatus:'valid'}});
  const {skill:instruction}=await hub.request<{skill:{id:string}}>('skill.create',{params:{name:'fixture-instruction',displayName:'Fixture instruction',description:'Fixture only',sourceType:'builtin',config:{type:'builtin',commandName:'fixture-instruction'},enabled:false,validationStatus:'valid'}});
  const {sessionId}=await hub.request<{sessionId:string}>('session.create',{workspacePath:join(run,'workspace'),config:{model:'haiku',provider:'anthropic',queryMode:'manual',sdkToolsPreset:['Read']}});
  const source={session:{id:sessionId},skills:app.db.skills.findAll(),registry:app.db.appMcpServers.list(),overrides:app.db.mcpEnablement.listAll()};
  await hub.request('tools.save',{sessionId,tools:{disabledSkills:[wrapper.id,instruction.id]}});
  const captured=app.db.captureSessionRuntimeSettings(sessionId)!;
  const config=JSON.parse(captured.config) as Session['config'];
  const translated=translateLegacyToolPreference(source,config,{kind:'skills',disabledSkills:[]});
  assert(translated.ok);
  assert.equal(translated.changes.length,2);
  let commits=0;
  const deps:SessionToolChoiceChangeDependencies={
    capture:()=>captured,
    catalog:()=>source,
    pinnedSlotVetoes:snapshot=>pinnedSlotVetoes(app!.db.getDatabase(),snapshot.metadata),
    commit:async(snapshot,patch)=>{commits++;return app!.db.casSessionRuntimeSettings(snapshot,patch);},
  };
  const denied=await changeSessionToolChoice({sessionId,changes:translated.changes},{...deps,catalog:()=>({...source,denied:[`mcp:${server.id}`]})});
  assert.deepEqual(denied,{ok:false,reason:'policy-denied'});
  assert.equal(commits,0);
  assert.equal(app.db.captureSessionRuntimeSettings(sessionId)!.config,captured.config);
  const accepted=await changeSessionToolChoice({sessionId,changes:translated.changes},deps);
  assert(accepted.ok);
  assert.equal(commits,1);
  assert.equal(accepted.selection.choices[`mcp:${server.id}`]?.selected,true);
  assert.equal(accepted.selection.choices[`skill:${instruction.id}`]?.selected,true);
  await app.sessionManager.interruptInMemorySession(sessionId);
  const reloaded=(await hub.request<{session:Session}>('session.get',{sessionId})).session;
  assert.deepEqual(reloaded.config.toolSelection,accepted.selection);
  assert.deepEqual(reloaded.config.tools,config.tools);
  assert.deepEqual(reloaded.config.sdkToolsPreset,['Read']);
  const before={...source,skills:source.skills.map(skill=>({...skill,enabled:true})),registry:source.registry.map(entry=>({...entry,enabled:true}))};
  const after={...before,registry:before.registry.map(entry=>entry.id===server.id?{...entry,enabled:false}:entry)};
  const nextDefaults=projectLegacyToolDefaultUpdate(before,after,[{key:`mcp:${server.id}`,selected:false}],accepted.selection);
  assert(nextDefaults.ok);
  assert.equal(nextDefaults.selection.choices[`mcp:${server.id}`]?.selected,false);
  assert.equal(nextDefaults.selection.choices[`skill:${instruction.id}`]?.selected,true);
  const newConfig=prepareInitialSessionToolSelection(source,[],nextDefaults.selection);
  assert(newConfig.ok);
  assert.equal(newConfig.selection.choices[`mcp:${server.id}`]?.selected,false);
  const stillFrozen=(await hub.request<{session:Session}>('session.get',{sessionId})).session;
  assert.deepEqual(stillFrozen.config.toolSelection,accepted.selection);
  const space={id:'fixture-space',selection:nextDefaults.selection};
  assert.equal(selectSessionToolDefaults(source.session,accepted.selection,space),accepted.selection);
  assert.equal(selectSessionToolDefaults({...source.session,context:{spaceId:space.id}},accepted.selection,space),nextDefaults.selection);
  const clear=translateLegacyToolPreference(source,config,{kind:'mcp',serverId:server.id,enabled:null},nextDefaults.selection);
  assert(clear.ok);
  assert.deepEqual(clear.changes,[{key:`mcp:${server.id}`,selected:false}]);
  const snapshot=app.db.captureSessionRuntimeSettings(sessionId)!;
  await hub.request('session.update',{sessionId,config:{autoScroll:false}});
  const raced=await changeSessionToolChoice({sessionId,changes:clear.changes},{...deps,capture:()=>snapshot});
  assert.deepEqual(raced,{ok:false,reason:'superseded'});
  assert.equal(app.db.getSession(sessionId)!.config.toolSelection!.choices[`mcp:${server.id}`]?.selected,true);
  const projected=projectSessionToolInputs(source,reloaded.config.toolSelection!);
  assert(projected.ok);
  assert.deepEqual(projected.catalogServers.map(entry=>entry.alias),['fixture-wrapper']);
  assert.deepEqual((await client.listTools()).tools.map(tool=>tool.name),['navigate']);
  assert.equal((await hub.request<{state:string}>('session.getToolInventory',{sessionId})).state,'not_running');
  evidence.translated=translated;
  evidence.accepted=accepted.selection;
  evidence.reloaded=reloaded.config.toolSelection;
  evidence.nextDefaults=nextDefaults.selection;
  evidence.existingSessionStayedFrozen=true;
  evidence.policyRefusedWholeBatch=true;
  evidence.staleBatchRefused=true;
  evidence.pass=true;
  console.log('PASS compatibility Build: multi-choice CAS, policy/stale refusal, RPC reload, default-only changes, native preset retained; no active consumer');
} finally {
  await transport?.close();
  await app?.cleanup();
  await client.close();
  await mcp.close();
  writeFileSync(join(run,'evidence/legacy-tool-preferences.json'),JSON.stringify(evidence,null,2));
}
