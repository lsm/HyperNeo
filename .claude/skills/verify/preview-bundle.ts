import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, realpathSync, renameSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Database } from '../../../packages/daemon/src/storage/sqlite-compat.ts';
import { createArtifactRegistration } from '../../../packages/daemon/src/lib/artifacts/register-operation.ts';
import { createArtifactReadOperations } from '../../../packages/daemon/src/lib/artifacts/read-operations.ts';
import { createOperationRegistry } from '../../../packages/daemon/src/lib/operations/registry.ts';
import { invokeOperation } from '../../../packages/daemon/src/lib/operations/invoke.ts';
const root = realpathSync(resolve(process.argv[2] ?? ''));
assert.equal(process.env.NODE_ENV, 'test');
assert.equal(process.env.HOME, join(root, 'home'));
execFileSync('bun', [fileURLToPath(new URL('./preview-register.ts', import.meta.url)), root, 'seed'], { env: process.env });
const data = join(root, 'data');
const workspace = join(root, 'workspace');
const pixel = 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNk+M9QDwADhgGAWjR9awAAAABJRU5ErkJggg==';
const html = '<!doctype html><link rel="stylesheet" href="styles/theme.css"><h1 class="bundle">Bundled report</h1><img src="images/chart.png" alt="Captured chart" width="120" height="120"><img src="unlisted.png" alt="Unlisted"><script>parent.escape()</script><p>End of bundled report.</p>';
writeFileSync(join(workspace, 'report.html'), html);
writeFileSync(join(workspace, 'theme.css'), '.bundle{color:#13713d;background-image:url(../images/chart.png)}');
writeFileSync(join(workspace, 'chart.png'), Buffer.from(pixel, 'base64'));
writeFileSync(join(workspace, 'unlisted.png'), Buffer.from(pixel, 'base64'));
if (process.argv[3] === 'seed') { console.log('seeded explicit bundle fixture'); process.exit(0); }
let db = new Database(join(data, 'daemon.db'));
const caller = { source: 'mcp' as const, role: 'direct_task_worker' as const, sessionId: 'worker' };
const context = { kind: 'todo' as const, id: 'todo' };
const catalog = () => createOperationRegistry([createArtifactRegistration(() => db, data, join(root, 'home')), ...createArtifactReadOperations(() => db, data)]);
const call = async (name: string, input: unknown, who = caller) => {
 const result = await invokeOperation(catalog(), name, input, who);
 assert.equal(result.kind, 'completed', JSON.stringify(result));
 return (result as { kind: 'completed'; value: Record<string, unknown> }).value;
};
const input = { requestId: 'bundle-html', context, path: 'report.html', title: 'Bundled report' };
const css = await call('artifact.file.register', { ...input, requestId: 'bundle-css', path: 'theme.css', title: 'Theme' });
assert.equal(css.accepted, true, JSON.stringify(css));
const image = await call('artifact.file.register', { ...input, requestId: 'bundle-image', path: 'chart.png', title: 'Chart' });
assert.equal(image.accepted, true);
const cssId = (css.artifact as { artifactId: string }).artifactId;
const imageId = (image.artifact as { artifactId: string }).artifactId;
const bundle = [{ path: 'styles/theme.css', artifactId: cssId }, { path: 'images/chart.png', artifactId: imageId }];
const first = await call('artifact.file.register', { ...input, bundle });
assert.equal(first.accepted, true, JSON.stringify(first));
assert(!JSON.stringify(first).includes(workspace));
const artifactId = (first.artifact as { artifactId: string }).artifactId;
const prepared = await call('artifact.file.html', { artifactId });
assert.equal(prepared.accepted, true);
assert(String(prepared.document).includes('color:#13713d'));
assert(String(prepared.document).includes('data:image/png;base64,' + pixel));
assert(!String(prepared.document).includes('Unlisted'));
assert(!String(prepared.document).includes('<script'));
const source = await call('artifact.file.read', { artifactId });
assert.equal(Buffer.from(String(source.data), 'base64').toString(), html);
assert.deepEqual(await call('artifact.file.register', { ...input, bundle }), first);
assert.deepEqual(await call('artifact.file.register', { ...input, bundle: [...bundle].reverse() }), first);
assert.deepEqual(await call('artifact.file.register', { ...input, bundle: [{ ...bundle[0], path: 'other.css' }, bundle[1]] }), { accepted: false, reason: 'source_changed' });
assert.deepEqual(await call('artifact.file.register', { ...input, requestId: 'unknown-asset', bundle: [{ path: 'missing.png', artifactId: 'unknown' }] }), { accepted: false, reason: 'unavailable' });
const markdown = await call('artifact.file.register', { ...input, requestId: 'markdown', path: 'report.md', title: 'Markdown' });
assert.equal(markdown.accepted, true);
assert.deepEqual(await call('artifact.file.register', { ...input, requestId: 'wrong-kind', bundle: [{ path: 'a.css', artifactId: (markdown.artifact as { artifactId: string }).artifactId }] }), { accepted: false, reason: 'unsupported_type' });
assert.deepEqual(await call('artifact.file.register', { ...input, bundle }, { ...caller, sessionId: 'foreign' }), { accepted: false, reason: 'unavailable' });
mkdirSync(join(workspace, 'retained'));
for (const file of ['theme.css', 'chart.png', 'report.html']) renameSync(join(workspace, file), join(workspace, 'retained', file));
assert.deepEqual(await call('artifact.file.register', { ...input, bundle }), first);
assert.deepEqual(await call('artifact.file.html', { artifactId }), prepared);
db.close();
db = new Database(join(data, 'daemon.db'));
assert.deepEqual(await call('artifact.file.html', { artifactId }), prepared);
assert.deepEqual(await call('artifact.file.register', { ...input, bundle }), first);
db.prepare("UPDATE neo_todo_sessions SET ref = ? WHERE todo_id = 'todo'").run(JSON.stringify({ adapter: 'hyperneo', id: 'replacement' }));
assert.deepEqual(await call('artifact.file.html', { artifactId }), { accepted: false, reason: 'unavailable' });
db.close();
const evidence = { immutableAssets: true, exactSource: true, idempotent: true, foreignRefused: true, restarted: true, revoked: true, first, prepared };
writeFileSync(join(root, 'bundle-evidence.json'), JSON.stringify(evidence, null, 2));
console.log(JSON.stringify(evidence));
