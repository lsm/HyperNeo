import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { spawn } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync, copyFileSync, symlinkSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createDaemonApp } from '../../../packages/daemon/src/app.ts';
import { getConfig } from '../../../packages/daemon/src/config.ts';
import { WorkerAgentMemoryEmbedder } from '../../../packages/daemon/src/storage/repositories/agent-memory-worker-embedder.ts';
import { SDKBunWorkerBridge } from '../../../packages/daemon/tests/helpers/sdk-bun-worker-bridge.ts';
import { installTurnVectorWait } from './turn-vector-wait.ts';

const run = resolve(process.argv[2]);
const waitMs = Number(process.argv[3] ?? 1200);
const bridge = process.argv[4] === 'bridge';
assert(run.startsWith('/private/tmp/'));
assert.equal(process.env.NODE_ENV, 'test');
assert.equal(process.env.HOME, join(run, 'home'));
assert.equal(process.env.HYPERNEO_DATA_DIR, join(run, 'data'));
assert(!existsSync(join(run, 'data')));
for (const key of ['ANTHROPIC_API_KEY', 'ANTHROPIC_AUTH_TOKEN', 'CLAUDE_CODE_OAUTH_TOKEN', 'OPENAI_API_KEY']) assert(!process.env[key]);
for (const directory of ['home', 'data', 'bin', 'evidence']) mkdirSync(join(run, directory), { recursive: true });
copyFileSync('.claude/skills/verify/gh-stub.sh', join(run, 'bin/gh'));
symlinkSync(process.execPath, join(run, 'bin/bun'));
process.env.PATH = join(run, 'bin') + ':' + process.env.PATH;
const NativeWorker = globalThis.Worker;
const warm = WorkerAgentMemoryEmbedder.prototype.warm;
WorkerAgentMemoryEmbedder.prototype.warm = () => {};
const fixture = pathToFileURL(join(run, 'reader.ts')).href;
writeFileSync(join(run, 'reader.ts'), `import { installTurnVectorWait } from ${JSON.stringify(pathToFileURL(resolve('.claude/skills/verify/turn-vector-wait.ts')).href)}; installTurnVectorWait(${JSON.stringify(run)},${waitMs},'worker'); const pending=[]; globalThis.onmessage=e=>pending.push(e); await import(${JSON.stringify(pathToFileURL(resolve('packages/daemon/src/storage/sdk-status-worker.ts')).href)}); const dispatch=globalThis.onmessage; for(const event of pending) dispatch(event);`);
globalThis.Worker = function (url: string | URL, options?: WorkerOptions) {
  if (String(url).endsWith('/sdk-status-worker.ts')) return bridge ? new SDKBunWorkerBridge(fixture) : new NativeWorker(fixture, options);
  return new NativeWorker(url, options);
} as unknown as typeof Worker;
let app: Awaited<ReturnType<typeof createDaemonApp>> | undefined;
let timer: ReturnType<typeof setInterval> | undefined;
let probe: ReturnType<typeof spawn> | undefined;
const evidence: Record<string, unknown> = { runtime: Bun.version, waitMs, bridge, surface: 'app-wired work.turns.embed job / independent system.health RPC', limitation: 'Executing-thread wait models slow MIN/MAX storage; not a physical-disk reproduction or a <=250ms affected-job pass.' };
try {
  app = await createDaemonApp({ config: getConfig({ port: 0, host: '127.0.0.1', dbPath: join(run, 'data/daemon.db'), workspaceRoot: run }), disableWorktrees: true, disableGoalProcessing: true, verbose: false });
  await app.jobProcessor.stop();
  assert.notEqual(app.server.port, 8399);
  const db = app.db.getDatabase(), embedder = app.db.getEmbedder();
  const texts: string[] = [];
  embedder.embedPassage = async text => { texts.push(text); return Float32Array.from({ length: embedder.dimensions }, (_, i) => i === 0 ? text.length : 0); };
  const insert = db.prepare(`INSERT INTO message_search_content(kind,source_id,message_id,session_id,message_type,title,body,timestamp) VALUES (?,?,?,'synthetic','user','Synthetic retained turn',?,?)`);
  const body = 'Complete synthetic turn 🦊\n'.repeat(150);
  const rows = ['message', 'codex', 'claude', 'message', 'codex'].map((kind, i) => {
    const text = `${i} ${body}`;
    const id = Number(insert.run(kind, `source-${i}`, `message-${i}`, text, i).lastInsertRowid);
    return { id, text };
  });
  insert.run('task', 'task-source', 'task-message', body, 5);
  insert.run('message', 'short-source', 'short-message', 'short', 6);
  const originalVector = Float32Array.from({ length: embedder.dimensions }, (_, i) => i === 0 ? 7 : 0);
  db.prepare('INSERT INTO message_search_vectors(content_id,model,dimensions,embedding,embedded_at) VALUES (?,?,?,?,1)').run(rows[2].id, embedder.model, embedder.dimensions, new Uint8Array(originalVector.buffer));
  const digest = () => createHash('sha256').update(JSON.stringify(db.prepare('SELECT * FROM message_search_content ORDER BY id').all())).update(JSON.stringify(db.prepare('SELECT * FROM message_search_vectors WHERE content_id=?').get(rows[2].id))).digest('hex');
  evidence.before = digest();
  const url = `ws://127.0.0.1:${app.server.port}/ws`;
  probe = spawn(process.execPath, ['-e', `const ws=new WebSocket(${JSON.stringify(url)});let stop=false,id=0,at=0;const samples=[];const send=()=>{if(stop){console.log(JSON.stringify({samples}));ws.close();return;}at=performance.now();ws.send(JSON.stringify({id:String(++id),type:'REQ',method:'system.health',data:{},sessionId:'global',version:'1.0.0',timestamp:new Date().toISOString()}));};ws.onopen=()=>{console.log('READY');send();};ws.onmessage=e=>{const r=JSON.parse(e.data);if((r.requestId??r.id)!==String(id))return;if(r.error)throw new Error(JSON.stringify(r.error));samples.push(performance.now()-at);setTimeout(send,10);};process.stdin.on('data',()=>{stop=true;});setTimeout(()=>process.exit(2),30000).unref();`], { env: process.env, stdio: ['pipe', 'pipe', 'pipe'] });
  let output = '', errors = '';
  probe.stdout!.on('data', data => { output += String(data); });
  probe.stderr!.on('data', data => { errors += String(data); });
  const exited = new Promise((done, fail) => { probe!.once('exit', done); probe!.once('error', fail); });
  for (let i = 0; !output.includes('READY') && i < 500; i++) await Bun.sleep(10);
  assert(output.includes('READY'), errors);
  installTurnVectorWait(run, waitMs, 'main');
  let previous = performance.now(), lagMs = 0;
  timer = setInterval(() => { const now = performance.now(); lagMs = Math.max(lagMs, now - previous - 10); previous = now; }, 10);
  await Bun.sleep(30);
  const job = app.jobQueue.enqueue({ queue: 'work.turns.embed', payload: { scope: 'turns' } });
  const started = performance.now();
  app.jobProcessor.start();
  let result = app.jobQueue.getJob(job.id)!;
  for (let i = 0; !['completed', 'dead'].includes(result.status) && i < 1000; i++) { await Bun.sleep(20); result = app.jobQueue.getJob(job.id)!; }
  const jobMs = performance.now() - started;
  await app.jobProcessor.stop();
  await Bun.sleep(30);
  clearInterval(timer); timer = undefined;
  probe.stdin!.end('stop');
  assert.equal(await exited, 0, errors);
  const health = JSON.parse(output.trim().split('\n').at(-1)!).samples as number[];
  const reads = readFileSync(join(run, 'evidence/range-reads.jsonl'), 'utf8').trim().split('\n').map(line => JSON.parse(line));
  const vectors = db.prepare('SELECT content_id,model,dimensions,embedding FROM message_search_vectors ORDER BY content_id').all() as { content_id: number; model: string; dimensions: number; embedding: Uint8Array }[];
  Object.assign(evidence, { lagMs, maxHealthMs: Math.max(...health), healthReplies: health.length, jobMs, result, texts, reads, after: digest(), vectorIds: vectors.map(row => row.content_id) });
  assert.equal(result.status, 'completed');
  assert.deepEqual(result.result, { embedded: 4, remaining: 0 });
  assert.deepEqual(texts, [rows[3], rows[4], rows[1], rows[0]].map(row => Array.from(row.text).slice(0, 2000).join('')));
  assert.deepEqual(vectors.map(row => row.content_id), rows.map(row => row.id));
  for (const row of vectors) { assert.equal(row.model, embedder.model); assert.equal(row.dimensions, embedder.dimensions); const vector = new Float32Array(row.embedding.buffer, row.embedding.byteOffset, row.embedding.byteLength / 4); assert.equal(vector[0], row.content_id === rows[2].id ? 7 : texts[0].length); }
  assert.equal(evidence.before, evidence.after, 'complete source bodies or preexisting vector changed');
  assert(reads.length >= 3);
  console.log(JSON.stringify({ run, lagMs, maxHealthMs: evidence.maxHealthMs, jobMs, thread: reads[0].thread }));
  assert(lagMs < 1000, `main loop blocked ${lagMs}ms`);
  assert(Number(evidence.maxHealthMs) < 250, 'independent health exceeded250ms');
  assert(reads.every(read => read.thread === 'worker'), 'range still read on main');
  if (!waitMs) assert(jobMs < 250, 'ordinary-data job exceeded250ms');
} finally {
  if (timer) clearInterval(timer);
  probe?.kill();
  await app?.cleanup();
  globalThis.Worker = NativeWorker;
  WorkerAgentMemoryEmbedder.prototype.warm = warm;
  writeFileSync(join(run, 'evidence/observed.json'), JSON.stringify(evidence, null, 2));
}
