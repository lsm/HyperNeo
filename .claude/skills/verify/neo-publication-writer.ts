import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { createDaemonApp } from '../../../packages/daemon/src/app.ts';
import { getConfig } from '../../../packages/daemon/src/config.ts';
import { createOperationMcpHandler } from '../../../packages/daemon/src/lib/operations/mcp-adapter.ts';
import { NeoRepository } from '../../../packages/daemon/src/storage/repositories/neo-repository.ts';
import { subscribeToStructuredLogs } from '../../../packages/daemon/src/lib/logger.ts';

const [mode, run] = process.argv.slice(2);
assert(['baseline', 'verify'].includes(mode));
assert(run.startsWith('/private/tmp/'));
assert.equal(process.env.NODE_ENV, 'test');
assert.equal(process.env.HOME, join(run, 'home'));
assert.equal(process.env.HYPERNEO_DATA_DIR, join(run, 'data'));
await mkdir(join(run, 'evidence'), { recursive: true });
await writeFile(join(run, 'bin/gh'), '#!/bin/sh\nexit 73\n', { mode: 0o755 });
const sql: Record<string, unknown>[] = [];
const off = subscribeToStructuredLogs(log => { if (log.module === 'hyperneo:daemon:sqlite.query' && log.metadata.workerKind === 'db-gateway-write') sql.push(log.metadata); });
const app = await createDaemonApp({ config: getConfig({ host: '127.0.0.1', dbPath: join(run, 'data/daemon.db'), workspaceRoot: run }), port: 0, disableWorktrees: true, disableGoalProcessing: true, standalone: false, verbose: false });
let probe: ReturnType<typeof spawn> | undefined;
const raw = app.db.getDatabase(), prepare = raw.prepare.bind(raw);
const evidence: Record<string, unknown> = { mode, lockHoldMs: 1500 };
try {
  await app.jobProcessor.stop();
  assert.notEqual(app.server.port, 8399);
  const conversation = '20000000-0000-4000-8000-000000000001', root = `neo:${conversation}`;
  prepare("INSERT INTO sessions(id,title,workspace_path,created_at,last_active_at,status,type,config,metadata) VALUES (?,'Synthetic Neo',?,'2026-10-27','2026-10-27','active','worker','{}','{}')").run(root, run);
  new NeoRepository(raw).reserveBinding({ sessionId: root, kind: 'neo', projectId: null });
  const handler = createOperationMcpHandler(() => app.sessionManager.getOperationRegistry(), () => ({ sessionId: root, role: 'neo' }));
  const input = { requestId: 'publication-proof', shortText: 'Complete report', fullText: 'Complete publication bytes 🦊\n'.repeat(512) };
  const publish = async () => { const reply = await handler({ name: 'neo.publication.publish', input }); assert.notEqual(reply.isError, true, JSON.stringify(reply)); return JSON.parse(reply.content[0].text); };
  let mainWrites = 0;
  raw.prepare = ((query: string) => { if (/INSERT INTO neo_publications/i.test(query)) { mainWrites++; if (mode === 'verify') throw new Error('Publication SQL forbidden on daemon main'); } return prepare(query); }) as typeof raw.prepare;
  const program = `import {Database} from ${JSON.stringify(new URL('../../../packages/daemon/src/storage/sqlite-compat.ts', import.meta.url).href)}; const db=new Database(${JSON.stringify(join(run,'data/daemon.db'))});const ws=new WebSocket(${JSON.stringify(`ws://127.0.0.1:${app.server.port}/ws`)});let stop=false,id=0,at=0;const samples=[];const finish=()=>{db.close();console.log(JSON.stringify({samples}));ws.close();};const send=()=>{if(stop){finish();return;}at=performance.now();ws.send(JSON.stringify({id:String(++id),type:'REQ',sessionId:'global',method:'system.health',data:{},timestamp:new Date().toISOString(),version:'1.0.0'}));};ws.onopen=()=>{db.exec('BEGIN IMMEDIATE');console.log('LOCKED');setTimeout(()=>{db.exec('COMMIT');},1500);send();};ws.onmessage=e=>{const r=JSON.parse(e.data);if((r.requestId??r.id)!==String(id))return;if(r.error)throw new Error(JSON.stringify(r.error));samples.push(performance.now()-at);setTimeout(send,5);};process.stdin.on('data',()=>{stop=true;});setTimeout(()=>process.exit(2),15000).unref();`;
  probe = spawn(process.execPath, ['-e', program], { env: process.env, stdio: ['pipe', 'pipe', 'pipe'] });
  let output = '', errors = '';
  probe.stdout!.on('data', chunk => { output += String(chunk); });
  probe.stderr!.on('data', chunk => { errors += String(chunk); });
  const exited = new Promise<number | null>((resolve, reject) => { probe!.once('exit', resolve); probe!.once('error', reject); });
  for (let n = 0; n < 500 && !output.includes('LOCKED'); n++) await new Promise(resolve => setTimeout(resolve, 10));
  assert(output.includes('LOCKED'), errors || output);
  const at = performance.now();
  const first = await publish();
  evidence.publishMs = performance.now() - at;
  assert.equal(first.accepted, true, JSON.stringify(first));
  assert.equal(first.created, true);
  assert.equal(first.publication.fullText, input.fullText);
  const again = await publish();
  assert.equal(again.accepted, true);
  assert.equal(again.created, false);
  assert.equal(again.publication.sequence, first.publication.sequence);
  assert.equal(prepare('SELECT COUNT(*) AS n FROM neo_publications').get().n, 1);
  probe.stdin!.end('stop');
  assert.equal(await exited, 0, errors);
  const samples = JSON.parse(output.trim().split('\n').at(-1)!).samples as number[];
  evidence.healthSamples = samples.length;
  evidence.maxHealthMs = Math.max(...samples);
  evidence.mainWrites = mainWrites;
  evidence.workerSql = sql.filter(row => row.workerOperation === 'neo.publications.write');
  evidence.completeBytes = Buffer.byteLength(input.fullText);
  assert.equal(mainWrites, 0, 'Publication persistence ran on daemon main');
  assert(samples.length > 5 && Math.max(...samples) < 250, 'Health unavailable during native writer contention');
  evidence.passed = true;
} finally {
  probe?.kill();
  raw.prepare = prepare;
  await app.cleanup();
  off();
  await writeFile(join(run, 'evidence/observed.json'), JSON.stringify(evidence, null, 2));
}
