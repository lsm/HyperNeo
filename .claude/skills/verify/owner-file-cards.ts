process.env.HYPERNEO_SPACE ??= 'on';
import { createLocalSocket } from '../../../packages/daemon/src/lib/pairing/local-credential.ts';
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync, unlinkSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { createDaemonApp } from '../../../packages/daemon/src/app.ts';
import { getConfig } from '../../../packages/daemon/src/config.ts';
import { NeoRepository } from '../../../packages/daemon/src/storage/repositories/neo-repository.ts';
import { readPublicFileSource } from '../../../packages/daemon/src/storage/repositories/public-file-source.ts';
import { resolveArtifactSource } from '../../../packages/daemon/src/lib/artifacts/file-policy.ts';
import { createOperationMcpHandler } from '../../../packages/daemon/src/lib/operations/mcp-adapter.ts';
import { previewLinkedReferenceCandidates, previewReferenceCandidates } from '../../../packages/shared/src/types/artifact-reference.ts';
import { MessageHub, WebSocketClientTransport } from '../../../packages/shared/src/mod.ts';

const run = resolve(process.argv.at(-1)!);
const home = join(run, 'home'), workspace = join(home, '.hyperneo/Neo');
const report = join(run, 'reports/review-report.md');
assert.equal(process.env.NODE_ENV, 'test');
assert.equal(process.env.HOME, home);
assert.equal(process.env.HYPERNEO_DATA_DIR, join(run, 'data'));
for (const path of ['bin', 'reports', 'evidence', 'home/.hyperneo/Neo', 'repository']) mkdirSync(join(run, path), { recursive: true });
writeFileSync(join(run, 'bin/gh'), '#!/bin/sh\nexit 2\n', { mode: 0o700 });
writeFileSync(join(workspace, 'CLAUDE.md'), 'Synthetic private Neo instructions');
writeFileSync(join(run, 'repository/CLAUDE.md'), 'Synthetic PR file, a different owner');
writeFileSync(report, '# Review A\n');
const app = await createDaemonApp({ config: { ...getConfig({ host: '127.0.0.1', port: 0, dbPath: join(run, 'data/daemon.db') }), disableWorktrees: true }, verbose: false });
const hub = new MessageHub({ defaultSessionId: 'global' });
const transport = new WebSocketClientTransport({createSocket: createLocalSocket,  url: `ws://127.0.0.1:${app.server.port}/ws`, autoReconnect: false });
hub.registerTransport(transport);
const evidence: Record<string, unknown> = { port: app.server.port, workspace, report, bareResolvedPath: join(workspace, 'CLAUDE.md') };
try {
  await app.spaceRuntimeService.ready();
  await app.jobProcessor.stop();
  assert.notEqual(app.server.port, 8399);
  const conversationId = '10000000-0000-4000-8000-000000000001';
  const sessionId = `neo:${conversationId}`;
  await app.db.createSession({ id: sessionId, title: 'Synthetic Neo', workspacePath: workspace, createdAt: new Date().toISOString(), lastActiveAt: new Date().toISOString(), status: 'active', config: {}, metadata: {} } as never);
  const db = app.db.getDatabase();
  new NeoRepository(db).reserveBinding({ sessionId, kind: 'neo', projectId: null });
  const mcp = createOperationMcpHandler(() => app.sessionManager.getOperationRegistry(), () => ({ sessionId, role: 'neo' }));
  const text = `The PR changes \`CLAUDE.md\` and \`docs/guide.md\`. The review is \`${report}\`.`;
  const response = await mcp({ name: 'neo.publication.publish', input: { requestId: 'owner-path-proof', shortText: text, fullText: text } });
  assert(!response.isError, JSON.stringify(response));
  const published = JSON.parse(response.content[0].text);
  assert(published.accepted);
  const source = { kind: 'publication' as const, id: published.publication.publicationId };
  const owner = readPublicFileSource(db, source, { source: 'rpc', principal: 'local' });
  assert.equal(owner?.workspacePath, workspace);
  assert.deepEqual(resolveArtifactSource(owner!, 'CLAUDE.md', { home }), { reason: { accepted: false, reason: 'sensitive_path' } });
  assert(previewReferenceCandidates(text).some((r) => r.reference === 'CLAUDE.md'));
  assert.deepEqual(previewLinkedReferenceCandidates(text).map((r) => r.reference), [report]);
  const counts = () => ['artifact_files', 'artifact_file_identity'].map(t => db.prepare(`SELECT COUNT(*) AS n FROM ${t}`).get());
  const before = counts();
  await transport.initialize();
  const read = (reference: string) => hub.request<{ accepted: boolean; reason?: string; data?: string; path?: string }>('operation.invoke', { name: 'file.reference.read', input: { sourceMessageOrCard: source, reference } });
  assert.equal((await read('CLAUDE.md')).reason, 'forbidden');
  const first = await read(report);
  assert(first.accepted);
  assert.equal(first.path, report);
  assert.equal(Buffer.from(first.data!, 'base64').toString(), '# Review A\n');
  writeFileSync(report, '# Review B\n');
  const edited = await read(report);
  assert(edited.accepted);
  assert.equal(Buffer.from(edited.data!, 'base64').toString(), '# Review B\n');
  unlinkSync(report);
  assert.equal((await read(report)).reason, 'missing');
  assert.deepEqual(counts(), before);
  if (process.argv.includes('--seed')) writeFileSync(report, '# Review A\n');
  Object.assign(evidence, { passed: true, publicationId: source.id, bareRejected: true, policyReason: 'sensitive_path', wireReason: 'forbidden', cardReferences: previewLinkedReferenceCandidates(text), liveReadEditDelete: true, noNewRows: true });
} finally {
  await transport.close();
  await app.cleanup();
  writeFileSync(join(run, 'evidence/owner-file-cards.json'), JSON.stringify({ ...evidence, cleaned: true }, null, 2));
}
console.log(JSON.stringify(evidence));
