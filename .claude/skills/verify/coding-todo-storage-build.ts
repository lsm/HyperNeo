process.env.HYPERNEO_SPACE ??= 'on';
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { createDaemonApp } from '../../../packages/daemon/src/app.ts';
import { prepareCodingTodoStorage } from '../../../packages/daemon/src/lib/neo/packs/coding/schema/coding-tables.ts';
import { codingTodoStorage } from '../../../packages/daemon/src/lib/neo/packs/coding/todo-storage.ts';
import { getConfig } from '../../../packages/daemon/src/config.ts';
import { createLocalSocket } from '../../../packages/daemon/src/lib/pairing/local-credential.ts';
import { createOperationMcpHandler } from '../../../packages/daemon/src/lib/operations/mcp-adapter.ts';
import { NeoAskTodoRepository } from '../../../packages/daemon/src/storage/repositories/neo-ask-todo-repository.ts';
import { NeoRepository } from '../../../packages/daemon/src/storage/repositories/neo-repository.ts';
import type { DbOp } from '../../../packages/daemon/src/storage/db-gateway/db-op.ts';
import type { NeoAsk, NeoTodo } from '../../../packages/shared/src/types/neo-ask.ts';
import { MessageHub, WebSocketClientTransport } from '../../../packages/shared/src/mod.ts';

const run = resolve(process.argv.at(-1)!);
assert.equal(process.env.NODE_ENV, 'test');
assert.equal(process.env.HOME, join(run, 'home'));
assert.equal(process.env.HYPERNEO_DATA_DIR, join(run, 'data'));
for (const folder of ['workspace', 'bin', 'evidence']) mkdirSync(join(run, folder), { recursive: true });
writeFileSync(join(run, 'bin/gh'), '#!/bin/sh\nexit 1\n', { mode: 0o700 });
const network = globalThis.fetch;
globalThis.fetch = (() => { throw new Error('External HTTP disabled'); }) as typeof fetch;
const app = await createDaemonApp({ config: getConfig({ host: '127.0.0.1', port: 0, dbPath: join(run, 'data/daemon.db') }), verbose: false });
const db = app.db.getDatabase(), core = new NeoAskTodoRepository(db);
const root = 'neo:10000000-0000-4000-8000-000000000005';
const hub = new MessageHub({ defaultSessionId: 'global' });
const transport = new WebSocketClientTransport({ createSocket: createLocalSocket, url: `ws://127.0.0.1:${app.server.port}/ws`, autoReconnect: false });
hub.registerTransport(transport);
const command = <T>(mode: 'read' | 'write', method: string, ...args: unknown[]) => app.db.gateway.run({ name: `coding.todoStorage${mode === 'read' ? 'Reads' : 'Writes'}`, mode, run: () => { throw new Error('Candidate command ran on main'); } } as DbOp<unknown, T>, { method, args });
const visible = () => hub.request<{ ok: true; entry: { ask: NeoAsk; todos: NeoTodo[] } }>('operation.invoke', { name: 'neo.ask.read', input: { askId: 'ask' } });
const candidate = (id: string) => command<NeoTodo>('write', 'create', { id, askId: 'ask', draft: { title: id, doneWhen: 'Observed', check: null, instruction: null, named: null }, now: 10, repo: 'github.com/synthetic/candidate' });
const replay = app.db.gateway.onChanges;
const tables: string[] = [];
let recording = false, held = false;
app.db.gateway.onChanges = changes => { if (recording) tables.push(...changes.map(change => change.table)); replay(changes); };
const result: Record<string, unknown> = { runtimeCutover: false, surface: 'Real daemon RPC/MCP and registered reader/writer workers; candidate construction only' };
try {
  assert.notEqual(app.server.port, 8399);
  await app.spaceRuntimeService.ready();
  await app.jobProcessor.stop();
  await transport.connect();
  await app.db.createSession({ id: root, title: 'Synthetic storage build', workspacePath: join(run, 'workspace'), createdAt: new Date().toISOString(), lastActiveAt: new Date().toISOString(), status: 'active', config: { queryMode: 'manual' }, metadata: { messageCount: 0, totalTokens: 0, inputTokens: 0, outputTokens: 0, totalCost: 0, toolCallCount: 0 } });
  new NeoRepository(db).reserveBinding({ sessionId: root, kind: 'neo', projectId: null });
  core.openAsk({ id: 'ask', title: 'Keep history', request: 'Build only', sessionId: root, projectId: null, originMessageId: null, repo: 'github.com/synthetic/legacy', createdAt: 1 });
  assert.equal(db.prepare("SELECT name FROM sqlite_master WHERE name='pack_coding_todos'").get(), null);
  const mcp = createOperationMcpHandler(app.sessionManager.getOperationRegistry(), () => ({ sessionId: root, role: 'neo' }));
  const add = async () => {
    const reply = await mcp({ name: 'neo.todo.add', input: { askId: 'ask', title: 'Current public add', check: { pack: 'core', kind: 'evidence', params: {} } } });
    assert(!reply.isError, JSON.stringify(reply));
    const receipt = JSON.parse(reply.content[0].text);
    assert(receipt.ok && receipt.todo, JSON.stringify(receipt));
    assert.equal(receipt.todo.repo, 'github.com/synthetic/legacy');
    return receipt.todo as NeoTodo;
  };
  const first = await add();
  assert.equal(db.prepare("SELECT name FROM sqlite_master WHERE name='pack_coding_todos'").get(), null);
  result.startupAndPublicWritesUnchanged = true;
  const injected = new NeoAskTodoRepository(db, undefined, undefined, undefined, undefined, codingTodoStorage(db));
  await assert.rejects(command('read', 'facts', 'ask'), /no such table/);
  assert.throws(() => injected.getTodo(first.id), /no such table/);
  assert.equal(db.prepare("SELECT name FROM sqlite_master WHERE name='pack_coding_todos'").get(), null);
  result.readBeforePrepareFailsWithoutMutation = true;
  assert.throws(() => db.transaction(() => {
    prepareCodingTodoStorage(db);
    assert.deepEqual(db.prepare('SELECT repo FROM pack_coding_todos WHERE todo_id=?').get(first.id), { repo: first.repo });
    throw new Error('outer failure after successful preparation');
  })(), /outer failure after successful preparation/);
  assert.equal(db.prepare("SELECT name FROM sqlite_master WHERE name='pack_coding_todos'").get(), null);
  assert.equal(core.getTodo(first.id)?.repo, first.repo);
  result.outerPreparationSavepointRollback = true;
  await command('write', 'prepare');
  assert.equal((await command<NeoTodo>('read', 'project', first)).repo, first.repo);
  const afterPreparation = await add();
  assert.equal(db.prepare('SELECT repo FROM pack_coding_todos WHERE todo_id=?').get(afterPreparation.id), null);
  result.noAutomaticDualWrite = true;
  const before = await visible();
  db.exec("CREATE TRIGGER refuse_candidate BEFORE INSERT ON pack_coding_todos WHEN NEW.todo_id='failed' BEGIN SELECT RAISE(ABORT,'late pack failure'); END");
  recording = true;
  await assert.rejects(candidate('failed'), /late pack failure/);
  recording = false;
  assert.equal(tables.length, 0);
  assert.deepEqual(await visible(), before);
  assert.equal(core.getTodo('failed'), null);
  result.lateFailureRollback = true;
  db.exec('DROP TRIGGER refuse_candidate');
  db.exec('BEGIN IMMEDIATE'); held = true;
  recording = true;
  let replied = false;
  const pending = candidate('candidate');
  void pending.then(() => { replied = true; }, () => { replied = true; });
  await new Promise(done => setTimeout(done, 500));
  assert.equal(replied, false); assert.equal(tables.length, 0);
  assert.deepEqual(await visible(), before);
  await hub.request('system.health', {});
  db.exec('ROLLBACK'); held = false;
  const receipt = await pending;
  recording = false;
  assert.equal(receipt.repo, 'github.com/synthetic/candidate');
  assert(tables.includes('pack_coding_todos') && tables.includes('neo_todos') && tables.includes('neo_asks'));
  const card = await visible();
  assert.equal(card.entry.todos.find(todo => todo.id === 'candidate')?.repo, null);
  assert.equal(card.entry.ask.repo, 'github.com/synthetic/legacy');
  assert.equal((await command<NeoTodo>('read', 'project', receipt)).repo, receipt.repo);
  result.commitBeforeReceiptAndNotifications = true;
  result.publicReaderNotActivated = true;
  const projected = [injected.getTodo(receipt.id), ...injected.getTodos([receipt.id]), ...injected.listTodos('ask').filter(todo => todo.id === receipt.id), ...injected.listTodosForAsks(['ask']).filter(todo => todo.id === receipt.id), ...injected.listCheckable().filter(todo => todo.id === receipt.id), injected.getCheckable(receipt.id)];
  assert.deepEqual(projected.map(todo => todo?.repo), Array(6).fill(receipt.repo));
  assert.equal(core.getTodo(receipt.id)?.repo, null);
  result.explicitSeamProjectsSixReaders = true;
  await command('write', 'record', first.id, null);
  await command('write', 'prepare');
  assert.equal((await command<NeoTodo>('read', 'project', first)).repo, null);
  assert.equal((await visible()).entry.todos.find(todo => todo.id === first.id)?.repo, first.repo);
  assert.deepEqual(await command('read', 'facts', 'ask'), { legacy: 'github.com/synthetic/legacy', repositories: ['github.com/synthetic/candidate', 'github.com/synthetic/legacy'] });
  result.explicitNullAndRepeatPreparation = true;
  result.verified = true;
} finally {
  if (held) db.exec('ROLLBACK');
  recording = false;
  app.db.gateway.onChanges = replay;
  await transport.close(); hub.cleanup();
  await app.cleanup(); globalThis.fetch = network;
  result.resourcesStopped = true;
  writeFileSync(join(run, 'evidence/coding-todo-storage-build.json'), JSON.stringify(result, null, 2));
}
console.log(JSON.stringify(result));
