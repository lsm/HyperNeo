await writeFile(join(workspace, 'unsupported.pdf'), '%PDF synthetic');
await writeFile(join(workspace, '.env.txt'), 'synthetic secret');
await symlink(report, join(workspace, 'linked.md'));
const chunked = Buffer.from('🦊 text\n'.repeat(50000));
await writeFile(join(workspace, 'chunked.txt'), chunked);
const app = await createDaemonApp({ config: { ...getConfig({ port: 0, host: '127.0.0.1', dbPath: join(run, 'data/daemon.db'), workspaceRoot: run }), disableWorktrees: true }, standalone: false, verbose: false });
