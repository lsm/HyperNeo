  work.openAsk({ id: 'ask', projectId: null, sessionId: neoId, originMessageId: null, title: 'Synthetic', request: 'Synthetic', createdAt: 1 });
  work.addTodo('todo', 'ask', { title: 'Read `report.md`', doneWhen: '', check: null, instruction: '', named: null }, 1);
  const sessions = new NeoTodoSessionRepository(db);
  sessions.create('todo', { verb: 'start', adapter: 'hyperneo', place: { machine: 'local', name: 'Synthetic', folder: workspace } });
  sessions.recordRef('todo', { adapter: 'hyperneo', id: 'worker', daemon: 'remote' });
  const counts = () => [db.prepare('SELECT COUNT(*) AS n FROM artifact_files').get(), db.prepare('SELECT COUNT(*) AS n FROM artifact_file_identity').get()];
  const before = counts();
  assert.equal(existsSync(join(run, 'data/artifacts')), false);
  ws = createLocalSocket(`ws://127.0.0.1:${app.server.port}/ws`);
  await new Promise((resolve, reject) => { ws!.onopen = resolve; ws!.onerror = reject; });
  type Result = { accepted: boolean; reason?: string; kind?: string; version?: string; data?: string; nextOffset?: number; byteLength?: number; complete?: boolean };
  const call = (input: object) => new Promise<Result>((resolve, reject) => {
    const id = crypto.randomUUID();
    const timeout = setTimeout(() => reject(new Error('RPC timeout')), 10000);
    ws!.onmessage = event => { const reply = JSON.parse(String(event.data)); if ((reply.requestId ?? reply.id) !== id) return; clearTimeout(timeout); reply.error ? reject(new Error(JSON.stringify(reply.error))) : resolve(reply.data); };
    ws!.send(JSON.stringify({ id, type: 'REQ', sessionId: 'global', method: 'operation.invoke', data: { name: 'file.reference.read', input }, timestamp: new Date().toISOString(), version: '1.0.0' }));
  });
  const input = (reference: string, extra = {}) => ({ sourceMessageOrCard: { kind: 'message', id: source.id }, reference, ...extra });
