  assert.deepEqual(await tap('empty.txt'), { accepted: true, path: join(workspace,'empty.txt'), kind: 'text', version: (await tap('empty.txt')).version, byteLength: 0, nextOffset: 0, complete: true, data: '' });
  const a = await tap('report.md');
