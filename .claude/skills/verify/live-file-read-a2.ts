  await writeFile(report, changed);
  assert.equal((await tap('report.md', { version: a.version })).reason, 'file_changed');
  const b = await tap('report.md');
  assert.equal(b.accepted, true);
  assert.equal(Buffer.from(b.data!, 'base64').toString(), changed);
  assert.notEqual(a.version, b.version);
  await unlink(report);
  const missing = await tap('report.md');
  assert.equal(missing.reason, 'missing');
  assert.equal((await tap('gone/report.md')).reason, 'missing');
  evidence.readA = original;
  evidence.readB = changed;
  evidence.deleted = missing;
  assert.equal((await tap('notes.txt')).kind, 'text');
  for (const [path, reason] of [['large.txt', 'size_limit'], ['bad.txt', 'unsupported_type'], ['unsupported.pdf', 'unsupported_type'], ['.env.txt', 'forbidden'], ['linked.md', 'forbidden'], ['../escape.md', 'forbidden'], ['unmentioned.txt', 'forbidden']]) {
    assert.equal((await tap(path)).reason, reason, path);
  }
  const chunks: Buffer[] = [];
  let offset = 0;
  let version: string | undefined;
  while (true) {
    const part = await tap('chunked.txt', { offset, maxBytes: 262143, ...(version ? { version } : {}) });
    assert.equal(part.accepted, true);
    const bytes = Buffer.from(part.data!, 'base64');
    assert(bytes.length <= 262144);
    chunks.push(bytes);
    assert.equal(part.nextOffset, offset + bytes.length);
    version ??= part.version;
    assert.equal(part.version, version);
    offset = part.nextOffset!;
    if (part.complete) break;
  }
