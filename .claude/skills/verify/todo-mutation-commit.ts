import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, resolve } from 'node:path';
import { createDaemonApp } from '../../../packages/daemon/src/app.ts';
import { getConfig } from '../../../packages/daemon/src/config.ts';
import { NeoRepository } from '../../../packages/daemon/src/storage/repositories/neo-repository.ts';
import { NeoAskTodoRepository } from '../../../packages/daemon/src/storage/repositories/neo-ask-todo-repository.ts';
import type { DbOp } from '../../../packages/daemon/src/storage/db-gateway/db-op.ts';
import { MessageHub, WebSocketClientTransport } from '../../../packages/shared/src/mod.ts';
import type { NeoTodo } from '../../../packages/shared/src/types/neo-ask.ts';

const [mode, directory] = process.argv.slice(2), run = resolve(directory);
assert.equal(mode, 'verify');
assert.equal(process.env.NODE_ENV, 'test');
assert.equal(process.env.HOME, join(run, 'home'));
assert.equal(process.env.HYPERNEO_DATA_DIR, join(run, 'data'));
for (const path of ['workspace','bin','evidence']) mkdirSync(join(run,path),{recursive:true});
writeFileSync(join(run,'bin/gh'),'#!/bin/sh\nexit 1\n',{mode:0o700});
const network = globalThis.fetch;
globalThis.fetch = (() => { throw new Error('External HTTP disabled'); }) as typeof fetch;
const app = await createDaemonApp({config:getConfig({port:0,host:'127.0.0.1',dbPath:join(run,'data/daemon.db')}),verbose:false});
assert.notEqual(app.server.port,8399);
const hub = new MessageHub({defaultSessionId:'global'});
const transport = new WebSocketClientTransport({url:`ws://127.0.0.1:${app.server.port}/ws`});
hub.registerTransport(transport);
const db = app.db.getDatabase(), store = new NeoAskTodoRepository(db);
const prepare = db.prepare.bind(db), replay = app.db.gateway.onChanges;
let record = false, mainSql = 0, events = 0, held = false;
db.prepare = ((sql:string) => { if(record && /neo_todos|neo_asks|neo_questions|pack_coding_pr_claims/.test(sql)) mainSql++; return prepare(sql); }) as typeof db.prepare;
app.db.gateway.onChanges = changes => { if(record) events += changes.length; replay(changes); };
type Result = {ok:false;reason:string}|{ok:true;todo:NeoTodo;todos:NeoTodo[];records?:string[]};
const op:DbOp<object,Result> = {name:'neo.todoMutations',mode:'write',run:()=>{throw new Error('The mutation must run in the real writer worker');}};
const commit = (input:object, checked?:object) => app.db.gateway.run(op,{input,checked,now:10});
const visible = () => hub.request<{ok:true;entry:{todos:NeoTodo[];questions:{id:string;state:string}[]}}>('operation.invoke',{name:'neo.ask.read',input:{askId:'ask'}});
const result:Record<string,unknown> = {mutationRpcActivated:false};
try {
  await app.spaceRuntimeService.ready(); await app.jobProcessor.stop(); await transport.connect();
  const root='neo:10000000-0000-4000-8000-000000009016';
  await app.db.createSession({id:root,title:'Synthetic atomic mutation',workspacePath:join(run,'workspace'),createdAt:new Date().toISOString(),lastActiveAt:new Date().toISOString(),status:'active',config:{queryMode:'manual'},metadata:{messageCount:0,totalTokens:0,inputTokens:0,outputTokens:0,totalCost:0,toolCallCount:0}});
  new NeoRepository(db).reserveBinding({sessionId:root,kind:'neo',projectId:null});
  store.openAsk({id:'ask',projectId:null,sessionId:root,originMessageId:null,title:'Atomic work',request:'Keep full work',createdAt:1});
  const check={pack:'coding',kind:'pr_merged',params:{urls:[]}};
  for(const id of ['first','peer']) store.addTodo(id,'ask',{title:id,doneWhen:'Merged',check,instruction:null,named:null},1);
  const before=await visible(), text='Committed full report 🦊\n'.repeat(20000).trim();
  await hub.request('system.health',{});
  db.exec('BEGIN IMMEDIATE'); held=true; record=true;
  let settled=false, responseError:unknown;
  const pending=commit({kind:'edit',todoId:'first',done:'reported',evidence:text});
  void pending.then(()=>{settled=true;},error=>{responseError=error;settled=true;});
  await new Promise(resolve=>setTimeout(resolve,80));
  if(responseError) throw responseError;
  assert.equal(settled,false,'No success may precede commit');
  assert.equal(events,0,'No notification may precede commit');
  assert.deepEqual(await visible(),before);
  await hub.request('system.health',{});
  db.exec('ROLLBACK'); held=false;
  const receipt=await pending;
  assert(receipt.ok); assert(receipt.todo.report===text,'The committed receipt must preserve the entire report'); assert(events>0);
  record=false;
  assert((await visible()).entry.todos.find(todo=>todo.id==='first')?.report===text,'The public card must preserve the entire report');
  result.commitBeforeReply=true;
  result.notificationsAfterCommit=true;
  result.fullReport={bytes:Buffer.byteLength(text),sha256:createHash('sha256').update(text).digest('hex')};
  const previous=store.getTodo('peer')!.check;
  store.updateTodo(store.getTodo('peer')!,{check:{pack:'core',kind:'evidence',params:{path:join(run,'not-created')}}},3);
  record=true; const prior=events;
  const stale=await commit({kind:'close',todoId:'peer',reason:'Finished'},{check:previous,result:{done:true}});
  assert(!stale.ok && stale.reason.startsWith('todo_changed:')); assert.equal(events,prior);
  record=false; result.staleCheckRefused=true;
  store.askQuestion('reply','ask',{kind:'reply',todoId:'peer',text:'Answer first',options:null,multiple:false,yesLabel:null,noLabel:null},4);
  const withCard=await visible(); record=true;
  const blocked=await commit({kind:'close',todoId:'peer',reason:'Finished'});
  assert(!blocked.ok && blocked.reason.startsWith('card_unanswered:')); assert.equal(events,prior);
  record=false; assert.deepEqual(await visible(),withCard); result.unansweredCardRefused=true;
  db.exec("CREATE TRIGGER refuse_ask_touch BEFORE UPDATE ON neo_asks BEGIN SELECT RAISE(ABORT, 'synthetic rollback'); END");
  record=true;
  await assert.rejects(commit({kind:'remove',todoId:'peer',reason:'Replaced'}),/synthetic rollback/);
  assert.equal(events,prior); record=false;
  assert.deepEqual(await visible(),withCard); result.rollbackPreservesCard=true;
  db.exec('DROP TRIGGER refuse_ask_touch');
  store.settleAsk(store.getAsk('ask')!,'done','Human settled it',6);
  const settledCard=await visible(); record=true;
  const noop=await commit({kind:'edit',todoId:'peer',title:'Ignored'});
  assert(noop.ok && noop.records?.some(line=>line.startsWith('ask_settled:')));
  assert.equal(events,prior); record=false; assert.deepEqual(await visible(),settledCard);
  assert.equal(mainSql,0); result.mainSql=mainSql; result.settledNoop=true; result.verified=true;
} finally {
  if(held) db.exec('ROLLBACK');
  db.prepare=prepare; app.db.gateway.onChanges=replay;
  await transport.close(); await app.cleanup(); globalThis.fetch=network;
  result.resourcesStopped=true;
  writeFileSync(join(run,'evidence/todo-mutation-commit.json'),JSON.stringify(result,null,2).replaceAll(run,'<synthetic-run>'));
}
console.log(JSON.stringify(result).replaceAll(run,'<synthetic-run>'));
