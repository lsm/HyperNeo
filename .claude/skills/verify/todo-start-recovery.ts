import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, resolve } from 'node:path';
import { createDaemonApp } from '../../../packages/daemon/src/app.ts';
import { getConfig } from '../../../packages/daemon/src/config.ts';
import { NeoRepository } from '../../../packages/daemon/src/storage/repositories/neo-repository.ts';
import { NeoAskTodoRepository } from '../../../packages/daemon/src/storage/repositories/neo-ask-todo-repository.ts';
import { NeoTodoSessionRepository } from '../../../packages/daemon/src/storage/repositories/neo-todo-session-repository.ts';
import type { DbOp } from '../../../packages/daemon/src/storage/db-gateway/db-op.ts';
import { MessageHub, WebSocketClientTransport } from '../../../packages/shared/src/mod.ts';
import type { NeoAsk, NeoTodo } from '../../../packages/shared/src/types/neo-ask.ts';

const [mode,directory]=process.argv.slice(2),run=resolve(directory);
assert.equal(mode,'verify'); assert.equal(process.env.NODE_ENV,'test');
assert.equal(process.env.HOME,join(run,'home')); assert.equal(process.env.HYPERNEO_DATA_DIR,join(run,'data'));
for(const path of ['workspace','bin','evidence']) mkdirSync(join(run,path),{recursive:true});
writeFileSync(join(run,'bin/gh'),'#!/bin/sh\nexit 1\n',{mode:0o700});
const network=globalThis.fetch;
globalThis.fetch=(()=>{throw new Error('External HTTP disabled');}) as typeof fetch;
const app=await createDaemonApp({config:getConfig({port:0,host:'127.0.0.1',dbPath:join(run,'data/daemon.db')}),verbose:false});
assert.notEqual(app.server.port,8399);
const hub=new MessageHub({defaultSessionId:'global'}), transport=new WebSocketClientTransport({url:`ws://127.0.0.1:${app.server.port}/ws`});
hub.registerTransport(transport);
const db=app.db.getDatabase(),store=new NeoAskTodoRepository(db),sessions=new NeoTodoSessionRepository(db);
const prepare=db.prepare.bind(db),replay=app.db.gateway.onChanges;
let record=false,mainSql=0,held=false,neoEvents=0;
const tables:string[]=[];
db.prepare=((sql:string)=>{if(record && /neo_todos|neo_asks|neo_questions|neo_todo_sessions/.test(sql)) mainSql++; return prepare(sql);}) as typeof db.prepare;
app.db.gateway.onChanges=changes=>{if(record) tables.push(...changes.map(change=>change.table)); replay(changes);};
const off=hub.onEvent('neo.changed',()=>{neoEvents++;});
type Receipt={recovery:{todo:NeoTodo;ask:NeoAsk}|null;changed:boolean};
const recover=(id:string,now=10)=>app.db.gateway.run({name:'neo.todoRunnerWrites',mode:'write',run:()=>{throw new Error('Recovery must run in the writer worker');}} as DbOp<object,Receipt>,{method:'recover',args:[id,now]});
const visible=()=>hub.request<{ok:true;entry:{todos:NeoTodo[]}}>('operation.invoke',{name:'neo.ask.read',input:{askId:'ask'}});
const result:Record<string,unknown>={runtimeCallersMoved:false};
const seed=(id:string)=>{
  store.addTodo(id,'ask',{title:id,doneWhen:'Observed',check:null,instruction:'Continue work',named:null},1);
  sessions.create(id,{verb:'start',adapter:'hyperneo',place:{machine:'synthetic',name:'Fixture',folder:join(run,'workspace')}});
  store.claimStart(store.getTodo(id)!,2);
};
try {
  await app.spaceRuntimeService.ready(); await app.jobProcessor.stop(); await transport.connect();
  const root='neo:10000000-0000-4000-8000-000000009068';
  await app.db.createSession({id:root,title:'Synthetic recovery build',workspacePath:join(run,'workspace'),createdAt:new Date().toISOString(),lastActiveAt:new Date().toISOString(),status:'active',config:{queryMode:'manual'},metadata:{messageCount:0,totalTokens:0,inputTokens:0,outputTokens:0,totalCost:0,toolCallCount:0}});
  new NeoRepository(db).reserveBinding({sessionId:root,kind:'neo',projectId:null});
  store.openAsk({id:'ask',projectId:null,sessionId:root,originMessageId:null,title:'Recover full work',request:'Keep full work',createdAt:1});
  seed('recover');
  const report='Complete recovery report 🦊\n'.repeat(20000).trim();
  prepare('UPDATE neo_todos SET report=? WHERE id=?').run(report,'recover');
  store.askQuestion('stale-start','ask',{kind:'start',text:'Start?',startTodos:['recover'],options:null,multiple:false,yesLabel:null,noLabel:null},3);
  const before=await visible();
  db.exec("CREATE TRIGGER refuse_stamp BEFORE UPDATE ON neo_asks BEGIN SELECT RAISE(ABORT, 'synthetic rollback'); END");
  record=true;
  await assert.rejects(recover('recover'),/synthetic rollback/);
  record=false;
  assert.equal(tables.length,0); assert.equal(sessions.readStartInterrupted('recover'),false); assert.deepEqual(await visible(),before);
  db.exec('DROP TRIGGER refuse_stamp'); result.rollbackPreservesFlagAndCard=true;
  db.exec('BEGIN IMMEDIATE'); held=true; record=true;
  let replied=false,error:unknown;
  const pending=recover('recover'); void pending.then(()=>{replied=true;},caught=>{error=caught;replied=true;});
  await new Promise(resolve=>setTimeout(resolve,80)); if(error) throw error;
  assert.equal(replied,false); assert.equal(tables.length,0); assert.deepEqual(await visible(),before);
  await hub.request('system.health',{});
  db.exec('ROLLBACK'); held=false;
  const receipt=await pending; record=false;
  assert.equal(receipt.recovery?.todo.state,'failed'); assert.equal(receipt.recovery?.todo.report,report); assert(receipt.changed);
  assert.equal(sessions.readStartInterrupted('recover'),true);
  assert((await visible()).entry.todos.some(todo=>todo.id==='recover' && todo.state==='failed' && todo.report===report));
  assert(tables.includes('neo_todo_sessions')); assert(tables.includes('neo_questions'));
  const retry=await hub.request<{ok:boolean;reason:string}>('operation.invoke',{name:'neo.todo.retry',input:{todoId:'recover'}});
  assert(!retry.ok && retry.reason.startsWith('start_uncertain:'));
  result.commitBeforeReply=true; result.retryWarnsOfUncertainStart=true;
  result.fullReport={bytes:Buffer.byteLength(report),sha256:createHash('sha256').update(report).digest('hex')};
  seed('late'); assert(sessions.unrecordedStarts().includes('late'));
  sessions.recordRef('late',{adapter:'hyperneo',id:'bound-worker'},4);
  const bound=await visible(),prior=tables.length;
  record=true; assert.deepEqual(await recover('late'),{recovery:null,changed:false});
  assert.deepEqual(await recover('recover'),{recovery:null,changed:false});
  assert.deepEqual(await recover('missing'),{recovery:null,changed:false}); record=false;
  assert.deepEqual(await visible(),bound); assert.equal(tables.length,prior); assert.equal(sessions.readStartInterrupted('late'),false);
  result.lateBindingPreserved=true; result.repeatedAndMissingQuiet=true;
  seed('race'); record=true;
  const racing=await Promise.all([recover('race'),recover('race')]); record=false;
  assert.equal(racing.filter(receipt=>receipt.recovery).length,1); result.singleRecoveryWinner=true;
  assert.equal(mainSql,0); await hub.request('system.health',{}); assert.equal(neoEvents,0);
  result.mainSql=mainSql; result.noNeoEvents=true; result.verified=true;
} finally {
  if(held) db.exec('ROLLBACK'); off(); db.prepare=prepare; app.db.gateway.onChanges=replay;
  await transport.close(); await app.cleanup(); globalThis.fetch=network; result.resourcesStopped=true;
  writeFileSync(join(run,'evidence/todo-start-recovery.json'),JSON.stringify(result,null,2).replaceAll(run,'<synthetic-run>'));
}
console.log(JSON.stringify(result).replaceAll(run,'<synthetic-run>'));
