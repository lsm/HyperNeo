import { createLocalSocket } from '../../../packages/daemon/src/lib/pairing/local-credential.ts';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { createDaemonApp } from '../../../packages/daemon/src/app.ts';
import { getConfig } from '../../../packages/daemon/src/config.ts';
import { NeoRepository } from '../../../packages/daemon/src/storage/repositories/neo-repository.ts';
import { NeoAskTodoRepository } from '../../../packages/daemon/src/storage/repositories/neo-ask-todo-repository.ts';
import { NeoTodoSessionRepository } from '../../../packages/daemon/src/storage/repositories/neo-todo-session-repository.ts';
import { NeoPublicationRepository } from '../../../packages/daemon/src/storage/repositories/neo-publication-repository.ts';
import { NeoConversationAskRepository } from '../../../packages/daemon/src/storage/repositories/neo-conversation-ask-repository.ts';

const run = process.argv[2];
assert.equal(process.env.NODE_ENV, 'test');
assert.equal(process.env.HOME, join(run, 'home'));
assert.equal(process.env.HYPERNEO_DATA_DIR, join(run, 'data'));
await mkdir(join(run, 'evidence'), { recursive: true });
await mkdir(join(run, 'workspace'));
await mkdir(join(run, 'neo-workspace'));
await writeFile(join(run, 'bin/gh'), '#!/bin/sh\nexit 73\n', { mode: 0o755 });
await writeFile(join(run, 'workspace/report.md'), '# Worker report\n');
await writeFile(join(run, 'neo-workspace/internal-only.md'), '# Hidden prompt file\n');
await writeFile(join(run, 'neo-workspace/report.md'), '# Neo report\n');
const config = { ...getConfig({ port: 0, host: '127.0.0.1', dbPath: join(run, 'data/daemon.db'), workspaceRoot: run }), disableWorktrees: true };
const app = await createDaemonApp({ config, standalone: false, verbose: false });
let ws: WebSocket | undefined;
const evidence: Record<string, unknown> = {};
try {
  await app.jobProcessor.stop();
  assert.notEqual(app.server.port, 8399);
  const conversationId = '10000000-0000-4000-8000-000000000001';
  const root = `neo:${conversationId}`;
  for (const [id, workspace] of [[root, 'neo-workspace'], ['worker', 'workspace']])
    await app.db.createSession({ id, title: 'Synthetic', workspacePath: join(run, workspace), createdAt: new Date().toISOString(), lastActiveAt: new Date().toISOString(), status: 'active', config: { model: 'synthetic' }, metadata: {} } as never);
  const db = app.db.getDatabase();
  const neo = new NeoRepository(db);
  neo.reserveBinding({ sessionId: root, kind: 'neo', projectId: null });
  assert.equal(neo.conversationId(), conversationId);
  const work = new NeoAskTodoRepository(db);
  work.openAsk({ id: 'ask', projectId: null, sessionId: root, originMessageId: null, title: 'Synthetic', request: 'Synthetic', createdAt: 1 });
  work.addTodo('todo', 'ask', { title: 'Read `report.md`', doneWhen: '', check: null, instruction: '', named: null }, 1);
  const links = new NeoTodoSessionRepository(db);
  links.create('todo', { verb: 'start', adapter: 'hyperneo', place: { machine: 'local', name: 'Synthetic', folder: join(run, 'workspace') } });
  links.recordRef('todo', { adapter: 'hyperneo', id: 'worker' });
  const sdk = app.db.getSDKMessageRepo();
  const save = (session: string, text: string, type: 'user' | 'assistant' = 'assistant', uuid = crypto.randomUUID()) => {
    assert(sdk.saveSDKMessage(session, { type, uuid, session_id: session, parent_tool_use_id: null, inputKind: 'task', message: { role: type, content: [{ type: 'text', text }] } } as never));
    const row = db.prepare('SELECT id FROM sdk_messages WHERE session_id = ? AND sdk_uuid = ?').get(session, uuid) as { id: string } | null;
    assert(row);
    return row.id;
  };
  const ordinary = save('worker', 'Read `report.md`.');
  const hidden = save(root, 'Internal prompt: `internal-only.md`.', 'user');
  const humanId = crypto.randomUUID();
  new NeoConversationAskRepository(db).append({ conversationId, requestId: humanId, askOrigin: { sessionId: root, messageId: humanId }, content: 'Read `report.md`.' });
  const intake = save(root, 'Read `report.md`. Runtime-only `internal-only.md`.', 'user', humanId);
  const publicationId = crypto.randomUUID();
  const publications = new NeoPublicationRepository(db);
  assert(publications.append({ conversationId, publicationId, shortText: 'Read report', fullText: 'Read `report.md`.', links: [{ kind: 'work', id: 'todo', label: 'Report' }] }).accepted);
  const foreignPublication = crypto.randomUUID();
  assert(publications.append({ conversationId: crypto.randomUUID(), publicationId: foreignPublication, shortText: 'Hidden', fullText: 'Read `report.md`.', links: [{ kind: 'work', id: 'todo', label: 'Report' }] }).accepted);
  ws = createLocalSocket(`ws://127.0.0.1:${app.server.port}/ws`);
  await new Promise((resolve, reject) => { ws!.onopen = resolve; ws!.onerror = reject; });
  type Reply = { accepted?: boolean; reason?: string; data?: string; artifact?: { artifactId: string } };
  const call = (name: string, input: unknown) => new Promise<Reply>((resolve, reject) => {
    const id = crypto.randomUUID();
    const timer = setTimeout(() => reject(new Error('RPC timeout')), 10000);
    ws!.onmessage = event => { const reply = JSON.parse(String(event.data)); if ((reply.requestId ?? reply.id) !== id) return; clearTimeout(timer); if (reply.error) reject(new Error(JSON.stringify(reply.error))); else resolve(reply.data); };
    ws!.send(JSON.stringify({ id, type: 'REQ', sessionId: 'global', method: 'operation.invoke', data: { name, input }, timestamp: new Date().toISOString(), version: '1.0.0' }));
  });
  const resolve = (kind: string, id: string, reference: string, extra = {}) => call('file.reference.read', { sourceMessageOrCard: { kind, id }, reference, ...extra });
  const ordinaryRead = await resolve('message', ordinary, 'report.md');
  assert.equal(ordinaryRead.accepted, true);
  const content = ordinaryRead;
  assert.equal(Buffer.from(content.data!, 'base64').toString(), '# Worker report\n');
  const retired = await call('artifact.reference.resolve', { sourceMessageOrCard: { kind: 'message', id: ordinary }, reference: 'report.md', requestId: crypto.randomUUID() });
  assert.equal(retired.accepted, false);
  assert.equal(retired.reason, 'client_upgrade_required');
  evidence.compatibility = true;
  evidence.hidden = await resolve('message', hidden, 'internal-only.md');
  assert.equal((evidence.hidden as Reply).accepted, false, 'A hidden Neo SDK prompt must not grant a file reference');
  evidence.intakeHidden = await resolve('message', intake, 'internal-only.md');
  assert.equal((evidence.intakeHidden as Reply).accepted, false);
  assert.equal((await resolve('message', intake, 'report.md')).accepted, true);
  assert.equal((await resolve('publication', publicationId, 'report.md')).accepted, true);
  assert.equal((await resolve('publication', foreignPublication, 'report.md')).accepted, false);
  const { readPublicFileSource } = await import('../../../packages/daemon/src/storage/repositories/public-file-source.ts');
  const human = { source: 'rpc' as const, principal: 'local' as const };
  const before = db.prepare('SELECT COUNT(*) AS n FROM artifact_files').get();
  const source = readPublicFileSource(db, { kind: 'publication', id: publicationId }, human);
  assert.equal(source?.owner.id, root);
  assert.equal(source?.workspacePath, join(run, 'neo-workspace'));
  const message = readPublicFileSource(db, { kind: 'message', id: ordinary }, human);
  assert.equal(message?.owner.id, 'worker');
  assert.equal(message?.workspacePath, join(run, 'workspace'));
  assert.equal(readPublicFileSource(db, { kind: 'message', id: intake }, human)?.text.join('\n'), 'Read `report.md`.');
  assert.equal(readPublicFileSource(db, { kind: 'todo', id: 'todo' }, { source: 'mcp', role: 'neo', sessionId: root }), null);
  links.recordRef('todo', { adapter: 'hyperneo', id: 'worker', daemon: 'remote' });
  const remote = readPublicFileSource(db, { kind: 'todo', id: 'todo' }, human);
  assert.equal(remote?.owner.daemon, 'remote');
  assert.equal(remote?.workspacePath, null);
  assert.equal((await resolve('todo', 'todo', 'report.md')).reason, 'owner_unavailable');
  assert.deepEqual(db.prepare('SELECT COUNT(*) AS n FROM artifact_files').get(), before);
  links.recordRef('todo', { adapter: 'hyperneo', id: 'worker' });
  db.prepare('UPDATE sessions SET workspace_path = NULL WHERE id = ?').run('worker');
  assert.equal(readPublicFileSource(db, { kind: 'todo', id: 'todo' }, human)?.workspacePath, null);
  assert.equal((await resolve('todo', 'todo', 'report.md')).accepted, false);
  const notVisible = save('worker', 'Read `report.md`.');
  db.prepare('UPDATE sdk_messages SET is_renderable = 0 WHERE id = ?').run(notVisible);
  assert.equal((await resolve('message', notVisible, 'report.md')).accepted, false);
  const mismatchedId = crypto.randomUUID();
  new NeoConversationAskRepository(db).append({ conversationId, requestId: mismatchedId, askOrigin: { sessionId: 'worker', messageId: mismatchedId }, content: 'Read `report.md`.' });
  const mismatched = save(root, 'Read `report.md`.', 'user', mismatchedId);
  assert.equal((await resolve('message', mismatched, 'report.md')).accepted, false);
  db.prepare('DELETE FROM neo_session_bindings WHERE session_id = ?').run(root);
  assert.equal(readPublicFileSource(db, { kind: 'publication', id: publicationId }, human), null);
  assert.equal((await resolve('publication', publicationId, 'report.md')).accepted, false);
  evidence.publicText = true;
  evidence.ownerWorkspace = true;
  evidence.liveReadEditDelete = 'not applicable to A1; covered by A2';
  evidence.passed = true;
} finally {
  ws?.close();
  await app.cleanup();
  evidence.resourcesClosed = true;
  await writeFile(join(run, 'evidence/observed.json'), JSON.stringify(evidence, null, 2));
}
console.log(JSON.stringify(evidence));
