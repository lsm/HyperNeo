import assert from 'node:assert/strict';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { createDaemonApp } from '../../../packages/daemon/src/app.ts';
import { getConfig } from '../../../packages/daemon/src/config.ts';
import { createOperationMcpHandler } from '../../../packages/daemon/src/lib/operations/mcp-adapter.ts';
import { invokeOperation } from '../../../packages/daemon/src/lib/operations/invoke.ts';
import { NeoRepository } from '../../../packages/daemon/src/storage/repositories/neo-repository.ts';
import { NeoAskTodoRepository } from '../../../packages/daemon/src/storage/repositories/neo-ask-todo-repository.ts';
import { SessionGoalRepository } from '../../../packages/daemon/src/storage/repositories/session-goal-repository.ts';

const run = resolve(process.argv[2]);
assert.equal(process.env.NODE_ENV, 'test');
assert.equal(process.env.HOME, join(run, 'home'));
assert.equal(process.env.HYPERNEO_DATA_DIR, join(run, 'data'));
assert(!existsSync(join(run, 'data')));
mkdirSync(join(run, 'evidence'), { recursive: true });
const evidence: Record<string, unknown> = {};
const app = await createDaemonApp({ config: getConfig({ port: 0, host: '127.0.0.1', dbPath: join(run, 'data/daemon.db') }), verbose: false });
try {
  await app.jobProcessor.stop();
  assert.notEqual(app.server.port, 8399);
  const sender = 'neo:10000000-0000-4000-8000-000000000003';
  const db = app.db.getDatabase();
  db.prepare("INSERT INTO sessions (id,title,workspace_path,created_at,last_active_at,status,config,metadata) VALUES (?, 'Synthetic Neo', '/tmp', '2026-11-07T00:00:00Z', '2026-11-07T00:00:00Z', 'active', '{}', '{}')").run(sender);
  new NeoRepository(db).reserveBinding({ sessionId: sender, kind: 'neo', projectId: null });
  const registry = () => app.sessionManager.getOperationRegistry();
  const handler = createOperationMcpHandler(registry, () => ({ sessionId: sender, role: 'neo' }));
  const mcp = async (name: string, input: unknown) => {
    const result = await handler({ name, input });
    assert(!result.isError, JSON.stringify(result));
    return JSON.parse(result.content[0].text);
  };
  const human = async (name: string, input: unknown) => {
    const child = Bun.spawn([process.execPath, '.claude/skills/verify/rpc.ts', name, JSON.stringify(input)], { env: { ...process.env, VERIFY_PORT: String(app.server.port) }, stdout: 'pipe', stderr: 'pipe' });
    const [stdout, stderr, status] = await Promise.all([new Response(child.stdout).text(), new Response(child.stderr).text(), child.exited]);
    assert.equal(status, 0, stderr);
    return JSON.parse(stdout).reply;
  };
  const draft = { title: 'Synthetic step', check: { pack: 'core', kind: 'evidence', params: { path: join(run, 'evidence/complete') } }, after: [] };
  const refusedStart = await mcp('work.start', { adapter: 'hyperneo', title: 'Synthetic work', message: 'Start' });
  evidence.refusedStart = refusedStart;
  assert.equal(refusedStart.ok, false);
  assert.equal(refusedStart.reason, 'todo_required');
  const target = '00000000-0000-4000-8000-000000000010';
  db.prepare("INSERT INTO sessions (id,title,workspace_path,created_at,last_active_at,status,config,metadata) VALUES (?, 'Synthetic worker', '/tmp', '2026-11-07T00:00:00Z', '2026-11-07T00:00:00Z', 'active', '{}', '{}')").run(target);
  const notice = { ref: { adapter: 'hyperneo', id: target }, message: 'Reply', notice: true };
  evidence.unsolicited = await mcp('work.send', notice);
  assert.equal((evidence.unsolicited as { ok: boolean }).ok, false);
  db.prepare("INSERT INTO neo_session_messages (conversation_id,message_id,from_session,to_session,text,created_at) VALUES ('synthetic','message',?,?, 'Question', '2026-11-07T00:00:00Z')").run(target, sender);
  evidence.reply = await mcp('work.send', notice);
  assert.equal((evidence.reply as { ok: boolean }).ok, true, JSON.stringify(evidence.reply));
  const initialRefusal = await mcp('neo.ask.open', { title: 'Invalid proposal', request: 'Synthetic test', todos: [draft] });
  evidence.initialRefusal = initialRefusal;
  assert.equal(initialRefusal.ok, false);
  const afterInvalid = await invokeOperation(registry(), 'neo.snapshot', {}, { source: 'rpc', principal: 'local' });
  assert.equal((afterInvalid as { value: { todoAsks: unknown[] } }).value.todoAsks.length, 0);

  const reply = await handler({ name: 'neo.ask.open', input: { title: 'Synthetic proposal', request: 'Improve the synthetic workflow because it is confusing' } });
  evidence.open = reply;
  assert(!reply.isError);
  const opened = JSON.parse(reply.content[0].text);
  assert.equal(opened.ok, true);
  const snapshot = await invokeOperation(registry(), 'neo.snapshot', {}, { source: 'rpc', principal: 'local' });
  evidence.snapshot = snapshot;
  assert.equal(snapshot.kind, 'completed');
  const cards = (snapshot as { value: { todoAsks: { ask: { id: string }; questions?: { kind: string; state: string }[] }[] } }).value.todoAsks;
  const proposal = cards.find((entry) => entry.ask.id === opened.ask.id);
  assert(proposal, 'proposal appears in human snapshot');
  assert(proposal.questions?.some((question) => question.kind === 'yesno' && question.state === 'open'), 'proposal has an open human decision card');
  const question = proposal.questions!.find((item) => item.kind === 'yesno') as { id: string } | undefined;
  assert(question);
  evidence.retry = await mcp('neo.ask.open', { title: 'Synthetic proposal', request: 'Improve the synthetic workflow because it is confusing', todos: [draft] });
  assert.equal((evidence.retry as { ok: boolean }).ok, false);
  const before = await mcp('neo.todo.add', { ...draft, askId: opened.ask.id });
  evidence.before = before;
  assert.equal(before.ok, false);
  const answered = await human('neo.question.answer', { questionId: question.id, answer: 'yes' });
  evidence.answered = answered;
  assert.equal(answered.ok, true);
  const after = await mcp('neo.todo.add', { ...draft, askId: opened.ask.id });
  evidence.after = after;
  assert.equal(after.ok, true, JSON.stringify(after));
  const store = new NeoAskTodoRepository(db);
  const sourceSession = { id: 'synthetic-worker', adapter: 'hyperneo', name: 'Worker', label: 'Synthetic worker', provider: 'HyperNeo', link: null };
  const seed = (id: string, cause?: string) => {
    store.openAsk({ id, sessionId: sender, projectId: null, originMessageId: `neo-track:synthetic:${id}`, title: id, request: 'Synthetic tracked request', createdAt: 1 });
    return store.askQuestion(`${id}-question`, id, { text: 'Which option?', kind: 'choice', options: ['First', 'Second'], multiple: false, noLabel: null, yesLabel: null, sourceSession, cause }, 1);
  };
  seed('historical');
  evidence.historical = await mcp('neo.todo.add', { ...draft, title: 'Historical step', askId: 'historical' });
  assert.equal((evidence.historical as { ok: boolean }).ok, true);
  store.openAsk({ id: 'session-request', sessionId: sender, projectId: null, originMessageId: 'session-request-message', title: 'Session request', request: 'Answer the session', createdAt: 1 });
  store.addTodo('request-reply', 'session-request', { title: 'Reply', doneWhen: 'Answered', check: null, instruction: null, named: { requestFrom: 'synthetic-worker' } }, 1);
  evidence.requestRefusal = await mcp('neo.todo.add', { ...draft, title: 'Request work', askId: 'session-request' });
  assert.equal((evidence.requestRefusal as { ok: boolean }).ok, false);
  const relayed = seed('new-relay', 'relay-session-proposal');
  evidence.relayBefore = await mcp('neo.todo.add', { ...draft, title: 'Relayed step', askId: 'new-relay' });
  assert.equal((evidence.relayBefore as { ok: boolean }).ok, false);
  evidence.relayAnswer = await human('neo.question.answer', { questionId: relayed.id, answer: ['First'] });
  assert.equal((evidence.relayAnswer as { ok: boolean }).ok, true);
  evidence.relayAfter = await mcp('neo.todo.add', { ...draft, title: 'Relayed step', askId: 'new-relay' });
  assert.equal((evidence.relayAfter as { ok: boolean }).ok, true);
  const goal = new SessionGoalRepository(db).create(sender, { title: 'Synthetic goal', doneTest: 'Observed', mandateRef: 'mandate.md', mandateRev: '0123456789012345678901234567890123456789' }, 1);
  const cycle = await mcp('neo.ask.open', { title: 'Goal proposal', request: 'Advance the goal because it is due', goalId: goal.id });
  const cycleCards = store.listQuestions(cycle.ask.id);
  evidence.goal = { cycle, cards: cycleCards };
  assert.equal(cycleCards.length, 1);
  assert.equal(cycleCards[0]!.state, 'open');
  const finished = await mcp('neo.ask.open', { title: 'Finished proposal', request: 'Complete the synthetic task' });
  const finishedCard = store.listQuestions(finished.ask.id)[0]!;
  assert.equal((await human('neo.question.answer', { questionId: finishedCard.id, answer: 'yes' })).ok, true);
  store.openAsk({ id: 'finished-child', parentId: finished.ask.id, sessionId: sender, projectId: null, originMessageId: null, title: 'Historical child', request: 'Preserve settled retry', createdAt: 1 });
  const settled = await mcp('neo.ask.settle', { askId: finished.ask.id, status: 'done', outcome: 'Synthetic work completed' });
  assert.equal(settled.ok, true, JSON.stringify(settled));
  const settledRetry = await mcp('neo.ask.open', { title: 'Finished proposal', request: 'Complete the synthetic task', todos: [draft] });
  evidence.settledRetry = settledRetry;
  assert.equal(settledRetry.ok, true, JSON.stringify(settledRetry));
  assert(settledRetry.records?.some((record: string) => record.startsWith('ask_settled:')));
  const second = await mcp('neo.ask.open', { title: 'Declined proposal', request: 'A separate synthetic change' });
  const secondSnapshot = await invokeOperation(registry(), 'neo.snapshot', {}, { source: 'rpc', principal: 'local' });
  const secondCard = (secondSnapshot as { value: { todoAsks: { ask: { id: string }; questions: { id: string; kind: string }[] }[] } }).value.todoAsks.find((entry) => entry.ask.id === second.ask.id)?.questions.find((item) => item.kind === 'yesno');
  assert(secondCard);
  evidence.decline = await human('neo.question.answer', { questionId: secondCard.id, answer: 'no' });
  const read = await mcp('neo.ask.read', { askId: second.ask.id });
  evidence.declinedAsk = read;
  assert.equal(read.entry.ask.status, 'dropped');
  console.log('PASS: proposal blocks work until human approval, decline drops ask, and untracked start is refused.');
} finally {
  writeFileSync(join(run, 'evidence/new-work-source.json'), JSON.stringify(evidence, null, 2));
  await app.cleanup();
}
