import { createLocalSocket } from '../../../packages/daemon/src/lib/pairing/local-credential.ts';
import assert from 'node:assert/strict';
import { mkdir, writeFile, unlink } from 'node:fs/promises';
import { join } from 'node:path';
import { createDaemonApp } from '../../../packages/daemon/src/app.ts';
import { getConfig } from '../../../packages/daemon/src/config.ts';
import { NeoAskTodoRepository } from '../../../packages/daemon/src/storage/repositories/neo-ask-todo-repository.ts';

const run = process.argv[2];
assert.equal(process.env.NODE_ENV, 'test');
assert.equal(process.env.HOME, join(run, 'home'));
assert.equal(process.env.HYPERNEO_DATA_DIR, join(run, 'data'));
for (const name of ['workspace','root-workspace','evidence']) await mkdir(join(run,name), {recursive:true});
await writeFile(join(run,'bin/gh'), '#!/bin/sh\nexit 73\n', {mode:0o755});
await writeFile(join(run,'workspace/report.md'), '# Correct worker A');
await writeFile(join(run,'workspace/detail.md'), '# Public document');
await writeFile(join(run,'workspace/metadata-only.md'), '# Must not be shared');
await writeFile(join(run,'root-workspace/report.md'), '# Wrong root');
let app: Awaited<ReturnType<typeof createDaemonApp>> | undefined;
let ws: WebSocket | undefined;
const observed: Record<string,unknown> = {};
try {
  app = await createDaemonApp({config:{...getConfig({port:0,host:'127.0.0.1',dbPath:join(run,'data/daemon.db'),workspaceRoot:run}),disableWorktrees:true},standalone:false,verbose:false});
  await app.jobProcessor.stop();
  assert.notEqual(app.server.port,8399);
  for (const [id,folder] of [['neo','root-workspace'],['worker','workspace']]) await app.db.createSession({id,title:'Synthetic',workspacePath:join(run,folder),createdAt:new Date().toISOString(),lastActiveAt:new Date().toISOString(),status:'active',config:{},metadata:{}} as never);
  const db=app.db.getDatabase();
  const store=new NeoAskTodoRepository(db);
  store.openAsk({id:'ask',projectId:null,sessionId:'neo',originMessageId:'original',title:'Synthetic',request:'Synthetic',createdAt:1});
  const draft={text:'Read `report.md`.',document:'Full report: `detail.md`',kind:'reply' as const,options:null,multiple:false,noLabel:null,yesLabel:null,startTodos:null};
  const owner={adapter:'hyperneo',id:'worker',name:'metadata-only.md',label:'metadata-only.md',provider:'synthetic',link:null};
  store.askQuestion('worker-question','ask',{...draft,sourceSession:owner},1);
  store.askQuestion('root-question','ask',draft,1);
  store.askQuestion('remote-question','ask',{...draft,sourceSession:{...owner,daemon:'remote'}},1);
  store.askQuestion('native-question','ask',{...draft,sourceSession:{...owner,adapter:'claude-code',id:'native'}},1);
  const counts=()=>['artifact_files','artifact_file_identity'].map(table=>db.prepare(`SELECT COUNT(*) AS n FROM ${table}`).get());
  const before=counts();
  ws=createLocalSocket(`ws://127.0.0.1:${app.server.port}/ws`);
  await new Promise((resolve,reject)=>{ws!.onopen=resolve;ws!.onerror=reject;});
  const read=(id:string,reference='report.md',extra={})=>new Promise<{accepted:boolean;reason?:string;data?:string;path?:string}>((resolve,reject)=>{
    const requestId=crypto.randomUUID();
    const timeout=setTimeout(()=>reject(new Error('RPC timeout')),10000);
    ws!.onmessage=event=>{const reply=JSON.parse(String(event.data));if((reply.requestId??reply.id)!==requestId)return;clearTimeout(timeout);reply.error?reject(new Error(JSON.stringify(reply.error))):resolve(reply.data);};
    ws!.send(JSON.stringify({id:requestId,type:'REQ',sessionId:'global',method:'operation.invoke',data:{name:'file.reference.read',input:{sourceMessageOrCard:{kind:'question',id,...extra},reference}},timestamp:new Date().toISOString(),version:'1.0.0'}));
  });
  const text=(result:{accepted:boolean;data?:string})=>{assert(result.accepted,JSON.stringify(result));return Buffer.from(result.data!,'base64').toString();};
  const workerRead=await read('worker-question');
  assert.equal(text(workerRead),'# Correct worker A');
  assert.equal(workerRead.path,join(run,'workspace/report.md'),'live preview must expose its authorized owner path for ordinary questions');
  assert.equal(text(await read('root-question')),'# Wrong root');
  assert.equal(text(await read('worker-question','detail.md')),'# Public document');
  assert.equal((await read('worker-question','metadata-only.md')).reason,'forbidden');
  assert.equal((await read('worker-question','report.md',{revisionId:'invented'})).reason,'forbidden');
  assert.equal((await read('missing-question')).reason,'forbidden');
  assert.equal((await read('remote-question')).reason,'owner_unavailable');
  assert.equal((await read('native-question')).reason,'owner_unavailable');
  await writeFile(join(run,'workspace/report.md'),'# Correct worker B');
  assert.equal(text(await read('worker-question')),'# Correct worker B');
  await unlink(join(run,'workspace/report.md'));
  assert.equal((await read('worker-question')).reason,'missing');
  assert.deepEqual(counts(),before);
  Object.assign(observed,{passed:true,recordedOwner:true,rootFallback:true,publicDocument:true,metadataRefused:true,remoteAndUnknownWorkspaceRefused:true,currentReadEditDelete:true,noRowsOrBlobs:true});
} finally {ws?.close();await app?.cleanup();}
observed.resourcesClosed=true;
await writeFile(join(run,'evidence/question-source.json'),JSON.stringify(observed,null,2));
console.log(JSON.stringify(observed));
