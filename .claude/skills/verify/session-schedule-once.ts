import assert from 'node:assert/strict';
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { createDaemonApp } from '../../../packages/daemon/src/app.ts';
import { createLocalSocket } from '../../../packages/daemon/src/lib/pairing/local-credential.ts';
import { getConfig } from '../../../packages/daemon/src/config.ts';
import { MessageHub, WebSocketClientTransport } from '../../../packages/shared/src/mod.ts';
import { JobQueueProcessor, type JobHandler } from '../../../packages/daemon/src/storage/job-queue-processor.ts';
import { runMigrations } from '../../../packages/daemon/src/storage/schema/index.ts';

const run = resolve(process.argv[2]);
assert.equal(process.env.NODE_ENV, 'test');
assert.equal(process.env.HOME, join(run, 'home'));
assert.equal(process.env.HYPERNEO_DATA_DIR, join(run, 'data'));
assert(!existsSync(join(run, 'data/daemon.db')));
for (const name of ['data', 'bin', 'evidence']) mkdirSync(join(run, name), { recursive: true });
copyFileSync(new URL('./gh-stub.sh', import.meta.url), join(run, 'bin/gh'));
process.env.PATH = `${join(run, 'bin')}:${process.env.PATH}`;
let fire: JobHandler | undefined;
const register = JobQueueProcessor.prototype.register;
JobQueueProcessor.prototype.register = function (queue, handler, options) {
  if (queue === 'sessionSchedule.fire') fire = handler;
  return register.call(this, queue, handler, options);
};
const clock = Date.now;
let now = clock();
let app: Awaited<ReturnType<typeof createDaemonApp>> | undefined;
const hub = new MessageHub({ defaultSessionId: 'global' });
let transport: WebSocketClientTransport | undefined;
const evidence: Record<string, unknown> = { wakes: [] };
try {
  app = await createDaemonApp({ config: { ...getConfig({ port: 0, host: '127.0.0.1', dbPath: join(run, 'data/daemon.db'), workspaceRoot: run }), disableGoalProcessing: true, disableWorktrees: true }, verbose: false });
  assert.notEqual(app.server.port, 8399);
  await app.jobProcessor.stop();
  assert(fire, 'The real daemon did not register its schedule handler');
  transport = new WebSocketClientTransport({ url: `ws://127.0.0.1:${app.server.port}/ws`, autoReconnect: false, createSocket: url => createLocalSocket(url, join(run, 'data/local-rpc.credential')) });
  hub.registerTransport(transport); await transport.initialize();
  const call = (name: string, input: unknown = {}) => hub.request<any>('operation.invoke', { name, input });
  const db = app.db.getDatabase();
  const target = await app.sessionManager.createSession({ workspacePath: run, title: 'Reminder recipient' });
  const live = await app.sessionManager.getSessionForControl(target); assert(live);
  await live.stateManager.setIdle();
  const repeating = await call('schedule.session.create', { target: { adapter: 'hyperneo', id: target }, cadence: { kind: 'every', everyMs: 3_600_000 }, note: 'Repeat check' });
  assert(repeating.ok, JSON.stringify(repeating));
  const before = db.prepare('SELECT * FROM session_schedules WHERE id = ?').get(repeating.schedule.id);
  db.exec("DELETE FROM migration_markers WHERE key = 'migration_523'");
  runMigrations(db, () => {});
  const after = db.prepare('SELECT * FROM session_schedules WHERE id = ?').get(repeating.schedule.id) as Record<string, unknown>;
  const indexes = (db.prepare("SELECT name FROM sqlite_master WHERE type = 'index' AND tbl_name = 'session_schedules' AND name LIKE 'idx_%' ORDER BY name").all() as { name: string }[]).map(row => row.name);
  evidence.upgrade = { before, after, indexes };
  assert.deepEqual(after, { ...(before as object), once_at: null }, 'The rebuild changed an existing schedule');
  assert.deepEqual(indexes, ['idx_session_schedules_due', 'idx_session_schedules_target']);
  const past = await call('schedule.session.create', { target: { adapter: 'hyperneo', id: target }, cadence: { kind: 'once', at: now - 1000 }, note: 'Too late' });
  assert.deepEqual(past, { ok: false, reason: 'invalid_cadence: a one-shot time must be in the future.' });
  const at = now + 600_000;
  const created = await call('schedule.session.create', { target: { adapter: 'hyperneo', id: target }, cadence: { kind: 'once', at }, note: 'Call the venue' });
  assert(created.ok, JSON.stringify(created));
  const id = created.schedule.id;
  assert.equal(created.schedule.nextRunAt, at);
  const row = () => db.prepare('SELECT status, next_run_at, pending_job_id, last_outcome FROM session_schedules WHERE id = ?').get(id) as { status: string; next_run_at: number | null; pending_job_id: string | null; last_outcome: string | null };
  const mailbox = (due: number) => (db.prepare("SELECT payload FROM job_queue WHERE queue = 'mailbox' AND json_extract(payload, '$.messageUuid') = ?").get(`schedule:${id}:${due}`) as { payload: string } | null)?.payload ?? null;
  Date.now = () => now;
  const wake = async () => {
    const current = row(); now = current.next_run_at!;
    await fire!(app!.jobQueue.getJob(current.pending_job_id!)!);
    const result = { due: current.next_run_at!, ...row(), delivered: mailbox(current.next_run_at!) !== null };
    (evidence.wakes as unknown[]).push(result);
    return result;
  };
  await live.stateManager.setQueued('verify-busy');
  const busy = await wake();
  assert.equal(busy.due, at);
  assert.deepEqual([busy.last_outcome, busy.status, busy.delivered], ['skipped_busy', 'active', false]);
  assert.equal(busy.next_run_at, at + 60_000, 'A busy one-shot must retry a minute later');
  await live.stateManager.setIdle();
  const fired = await wake();
  assert.deepEqual([fired.last_outcome, fired.status, fired.delivered, fired.next_run_at, fired.pending_job_id], ['fired', 'done', true, null, null]);
  assert(String(mailbox(fired.due)).includes('Call the venue'));
  const deliveries = (db.prepare("SELECT COUNT(*) AS n FROM job_queue WHERE queue = 'mailbox' AND json_extract(payload, '$.messageUuid') LIKE ?").get(`schedule:${id}:%`) as { n: number }).n;
  assert.equal(deliveries, 1, 'A one-shot reminder delivered more than once');
  const listed = await call('schedule.session.list', { target: { adapter: 'hyperneo', id: target } });
  evidence.listed = listed;
  assert.deepEqual(listed.schedules.find((s: { id: string }) => s.id === id)?.cadence, { kind: 'once', at });
  console.log(`PASS one-shot reminder waited out a busy target, delivered once and ended done; the rebuild kept existing schedules. ${run}/evidence/schedule-once.json`);
} finally {
  Date.now = clock;
  writeFileSync(join(run, 'evidence/schedule-once.json'), JSON.stringify(evidence, null, 2));
  await transport?.close(); await app?.cleanup();
  JobQueueProcessor.prototype.register = register;
}
