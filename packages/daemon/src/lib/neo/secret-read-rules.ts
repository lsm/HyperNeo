const SECRET_NAMES = ['.env', '.env.*', '*.pem', '*.key'];

export function neoSecretReadRules(): string[] {
  return [
    ...SECRET_DIRS.map((dir) => `~/${dir}/**`),
    ...SECRET_FILES.flatMap((file) => [`~/${file}`, `~/**/${file}`]),
    ...SECRET_NAMES.map((name) => `~/**/${name}`),
  ].map((path) => `Read(${path})`);
}
